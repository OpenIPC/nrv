/**
 * Фоновый обработчик push-сообщений.
 *
 * Он нужен ровно для одного случая — входящий звонок. Сообщение о звонке
 * приходит БЕЗ уведомления, только данными: уведомление система показала бы
 * сама, но приложению его не отдала бы, пока приложение свёрнуто. А нам нужно
 * другое — чтобы приложение проснулось, подняло SIP-линию и показало экран
 * вызова, пока станция ещё звонит (она повторяет набор около двадцати секунд).
 *
 * Здесь же поднимаем экран: на заблокированном телефоне иначе виден только
 * значок в строке состояния, и вызов легко пропустить.
 *
 * Обработчик зарегистрирован в index.js, до запуска интерфейса: сообщение
 * может прийти и тогда, когда интерфейса нет вовсе.
 */

import { NativeModules, Platform } from 'react-native';
import messaging from '@react-native-firebase/messaging';

import { emitIncomingCall } from './push';

/** Нативные вызовы службы: работают и без отрисованного интерфейса. */
interface CallNative {
  incomingCall(title: string, text: string): void;
  wake(): void;
}

const native = (NativeModules as Record<string, CallNative | undefined>).NvrSipForeground;

/**
 * Регистрирует обработчик фоновых сообщений.
 *
 * Вызывается один раз при старте приложения (в том числе при старте «в фоне»,
 * когда система поднимает процесс ради сообщения).
 */
export function installBackgroundPush(): void {
  if (Platform.OS !== 'android') {
    return;
  }
  messaging().setBackgroundMessageHandler(async (message) => {
    const data = message.data ?? {};
    if (data.type !== 'incoming_call') {
      return;
    }

    // Показываем вызов на весь экран: это и будит аппарат, и даёт человеку
    // кнопку ответа, даже если интерфейс приложения ещё не поднялся.
    try {
      native?.incomingCall('Звонок в домофон', 'Кто-то звонит — ответьте или откройте дверь');
    } catch {
      // Прошивка может запретить полноэкранное уведомление — тогда остаётся
      // попытка поднять активность ниже.
    }
    try {
      native?.wake();
    } catch {
      // Запуск активности из фона разрешён не всегда; уведомление выше уже
      // показано, и по нему человек вернётся в приложение.
    }

    // Если интерфейс жив (приложение свёрнуто, но не выгружено), сообщаем
    // ему: он поднимет линию заново. Когда интерфейса нет, подписки пустые,
    // и пробуждение линии произойдёт уже после открытия приложения — станция
    // к этому времени ещё продолжает дозваниваться.
    emitIncomingCall(typeof data.number === 'string' ? data.number : '');
  });
}
