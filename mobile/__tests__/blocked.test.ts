import { ACCOUNT_BLOCKED_CODE, CLIENT_FORBIDDEN_CODE, toApiError } from '../src/net/api';

/**
 * Заблокированная учётная запись должна объясняться словами сервера.
 *
 * Проверка нужна потому, что ответ приходит с кодом 403 — тем же, что и
 * «нет прав». Если показывать общее сообщение про права, человек пойдёт
 * искать причину в правах и не поймёт, что нужно обратиться к администратору.
 */
describe('блокировка учётной записи', () => {
  it('показывает текст сервера', () => {
    const message =
      'Доступ в приложение заблокирован. Обратитесь к администратору. Разблокировка: 15.10.2026 09:00.';

    const error = toApiError(
      403,
      { code: ACCOUNT_BLOCKED_CODE, error: message },
      new Error('sip-calls'),
    );

    expect(error.message).toBe(message);
  });

  it('обычный запрет по правам остаётся прежним', () => {
    const error = toApiError(403, {}, new Error('cameras'));

    expect(error.message).toBe('Доступ запрещён: у пользователя нет прав');
  });

  it('без кода в ответе текст сервера не подменяется', () => {
    const error = toApiError(400, { error: 'неверный запрос' }, new Error('x'));

    expect(error.message).toBe('неверный запрос');
  });
});

/**
 * Закрытый клиент — другой случай, чем блокировка: учётная запись работает,
 * просто ей разрешён другой интерфейс. Текст тоже должен быть серверный:
 * «пользуйтесь веб-интерфейсом» вместо «нет прав».
 */
describe('закрытый клиент', () => {
  it('показывает текст сервера', () => {
    const message =
      'доступ через приложение для этой учётной записи закрыт. Обратитесь к администратору.';

    const error = toApiError(
      403,
      { code: CLIENT_FORBIDDEN_CODE, error: message },
      new Error('login'),
    );

    expect(error.message).toBe(message);
  });
});
