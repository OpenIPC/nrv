package domain

// Настройки абонента в виде строки таблицы Realtime.
//
// Зачем отдельный тип, а не запись прямо из сборщика конфигурации. Причин две.
// Первая: набор значений решает сервер (кодеки, DTMF, число контактов), а
// пишет в базу репозиторий — типу нужно описать то, что передаётся между
// ними, а не то, как это выглядит в SQL. Вторая: в таблицах Asterisk почти все
// поля текстовые, и соблазн «сложить туда что угодно» велик; с типом видно,
// какие поля заполняются осознанно.
type SipRealtimeEndpoint struct {
	// Number — он же id объекта: имя абонента, имя auth и имя aor.
	//
	// Одно имя на три объекта обязательно: Asterisk связывает их по строкам
	// `auth` и `aors` в настройках абонента, и разные имена — это лишняя
	// возможность ошибиться при разборе конфигурации глазами.
	Number string
	// Context — откуда приходят вызовы: from-devices у устройств,
	// from-apps у приложений. От него зависит, что абоненту разрешено.
	Context string
	// CallerID — подпись в формате «"Имя" <номер>»: её видно на экране
	// устройства и в журнале звонков.
	CallerID string
	Password string
	// Allow — кодеки через запятую: alaw,ulaw и, если включены видеозвонки,
	// видеокодек. Пустым не бывает: без кодека вызов не устанавливается.
	Allow string
	// DtmfMode — как передаются нажатия клавиш (коды открытия двери).
	DtmfMode string
	// WebRTC включает DTLS-SRTP и ICE. Нужен только приложениям: устройства
	// подключаются обычным SIP и эти расширения не поддерживают.
	WebRTC bool
	// MediaAddress — внешний адрес станции для приложений вне дома. Пусто,
	// если установка работает только в своей сети.
	MediaAddress string
	// RTPPortStart/End — диапазон портов разговора. Задаётся в настройках
	// телефонии, чтобы его можно было сузить под проброс на роутере.
	RTPPortStart int
	RTPPortEnd   int
	// MaxContacts — сколько регистраций одного абонента станция помнит
	// одновременно. Запас нужен: при переподключении старая регистрация
	// может ещё не истечь, и с пределом в один контакт новая отклонялась бы.
	MaxContacts int
	// QualifyFrequency — как часто станция сама проверяет устройство, секунды.
	QualifyFrequency int
}
