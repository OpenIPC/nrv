package domain

// Строка таблицы Asterisk `extensions` — одно правило набора.
//
// Почему правило описано не строкой текста, как в файле конфигурации, а
// набором полей. В таблице каждая строка самостоятельная: приоритеты задаются
// числами, а «то же, что выше» (`same => n`), как в файле, выразить нельзя.
// Поэтому приоритет здесь — обязательное поле, а не украшение: пропуск в
// нумерации означает, что станция не станет выполнять правило дальше этого
// места, и вызов оборвётся на середине.
type SipDialplanRow struct {
	// Context — где правило действует: from-devices у устройств,
	// from-apps у приложений.
	Context string
	// Exten — набранный номер. Может быть шаблоном (`_1XX`), тогда в конце
	// нужен `!` или совпадение по количеству цифр.
	Exten string
	// Priority — номер шага, начиная с единицы.
	Priority int
	// App — приложение Asterisk: Dial, Set, While, NoOp, Hangup…
	App string
	// AppData — аргументы приложения как есть, включая выражения вида
	// `${CUT(CALLLIST,&,${IDX})}`. Длина здесь не ограничена осознанно:
	// список обзвона группы бывает длинным.
	AppData string
}

// SipDialplanContexts — контексты, для которых сервер пишет правила.
//
// Список нужен при очистке: перед записью нового диаллана из таблицы
// удаляются строки именно этих контекстов, чтобы правка группы не оставила
// вчерашние правила рядом с сегодняшними.
var SipDialplanContexts = []string{"from-devices", "from-apps", SipDialplanAppLineContext}

// SipDialplanAppLineContext — контекст дозвона до линии приложения.
//
// Отдельный контекст, а не правило внутри общих: сюда попадают через
// локальный канал (Local/304@app-line), и здесь же лежит повтор набора,
// который даёт проснувшемуся телефону время зарегистрироваться.
const SipDialplanAppLineContext = "app-line"
