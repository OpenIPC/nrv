// Пакет configtransfer переносит настройки сервера между установками:
// собирает их в один файл и применяет на другом сервере.
//
// Настройки — это то, что задаёт человек: камеры и их расписания, СКУД,
// домофония, пользователи, уведомления. Данные сюда не входят, и это
// осознанное решение, а не упрощение. Видеоархив измеряется сотнями
// гигабайт и ссылается на файлы, которых на новом сервере нет, а журналы
// событий, логов и звонков описывают прошлое прежнего сервера — на новом
// месте они не значат ничего.
package configtransfer

// Format и Version — подпись файла переноса.
//
// По формату импорт отличает свой файл от чужого и говорит об этом
// человеку, а не пытается разобрать что попало.
const (
	Format  = "nvr-config"
	Version = 1
)

// configTables — таблицы, которые переносятся целиком.
//
// Порядок перечисления здесь не важен: при импорте он строится по связям
// между таблицами (см. orderTables), иначе вставка упиралась бы в ссылки
// на строки, которых ещё нет.
var configTables = []string{
	// Площадки и коммутаторы: к ним привязаны камеры и телефония.
	"sites",
	"switches",
	"switch_ports",

	// Пользователи и их права. Переносятся вместе с хешами паролей: иначе
	// после переезда в систему нельзя было бы войти под своими учётными
	// записями, а заводить их заново на каждом сервере — та же работа,
	// от которой и избавляет перенос.
	"users",

	// Камеры и всё, что к ним привязано: расписания записи, детекция,
	// настройки звука, присмотр за стримером, привязка к портам.
	"cameras",
	"detection_settings",
	"audio_settings",
	"majestic_watch",
	"camera_switch_port",

	// СКУД: контроллеры, двери, владельцы, карты, группы доступа, планы.
	"acs_controllers",
	"acs_doors",
	"acs_groups",
	"acs_holders",
	"acs_group_doors",
	"acs_holder_doors",
	"acs_holder_groups",
	"acs_cards",
	"acs_plans",
	"acs_plan_points",

	// Домофония: абоненты, группы вызова, правила, настройки медиа.
	"sip_accounts",
	"sip_groups",
	"sip_group_members",
	"sip_rules",
	"sip_switch_port",
	"sip_settings",

	// Настройки сервера, уведомления и распознавание.
	"server_settings",
	"webhook_subscriptions",
	"known_faces",
	"known_plates",

	// Туннели: адреса и публичные ключи площадок. Приватные ключи устройств
	// в базе не хранятся, поэтому перенос не ломает существующие туннели.
	"wireguard_peers",
}

// dataTables — то, что остаётся на прежнем сервере.
//
// Список нужен не для переноса, а для защиты данных при импорте: таблицы,
// на которые каскадом ссылаются эти, нельзя чистить построчно (см.
// protectedTables).
var dataTables = []string{
	"recordings",
	"detection_events",
	"audio_events",
	"acs_events",
	"camera_logs",
	"sip_calls",
	"notification_log",
	"switch_port_events",
	"switch_mac_entries",
	"push_tokens",
}

// protectedTables — настройки, которые импорт не имеет права удалять
// построчно.
//
// На них каскадом ссылаются данные: стоит удалить камеру или коммутатор, и
// вместе с ними уйдёт видеоархив, детекции и журнал событий — то есть
// ровно то, чего перенос не касается вовсе. Для таких таблиц совпадение по
// уникальному полю остаётся ошибкой с понятным текстом: лучше остановиться
// и объяснить, чем молча снести архив.
var protectedTables = map[string]bool{
	"cameras":  true,
	"switches": true,
}
