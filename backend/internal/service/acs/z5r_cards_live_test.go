package acs

import (
	"context"
	"os"
	"testing"
)

// TestZ5RLiveListCards проверяет чтение карт с контроллера.
//
// Тест требует живого контроллера: команда read_cards отправляется только
// в ответ на обращение контроллера, и подделать это без устройства нельзя.
// Поэтому проверяется вся цепочка — очередь, отправка, приём списка.
//
// Запуск:
//
//	Z5R_TEST_IP=192.168.1.60 Z5R_TEST_PASS=96811621 \
//	  go test ./internal/service/acs/ -run TestZ5RLiveListCards -v
func TestZ5RLiveListCards(t *testing.T) {
	if os.Getenv("Z5R_TEST_CARDS") == "" {
		t.Skip("Z5R_TEST_CARDS не задана — тест с обращением к базе карт пропущен")
	}

	a := liveZ5R(t)
	ctx := context.Background()

	if err := a.Ping(ctx); err != nil {
		t.Fatalf("Ping: %v", err)
	}

	// Подписываемся на приём документов так же, как это делает обработчик
	// WEBJSON. Без подписки контроллеру некуда будет прислать список.
	//
	// Канал используется только для регистрации: сам список карт придёт
	// сюда после того, как контроллер заберёт команду, и ждать его в этом
	// тесте не нужно — тест проверяет отправку команды.
	key := a.ctrl.ID.String()
	cardsCh := z5rCards.subscribe(key, z5rCardsBuffer)
	defer z5rCards.unsubscribe(key)

	// Ставим команду в очередь.
	done := z5rQueue.enqueue(key, z5rCommand{Operation: opReadCards})

	// Ждём, пока контроллер обратится к нам и заберёт команду.
	select {
	case <-done:
		t.Log("команда read_cards отправлена контроллеру")
	case <-ctx.Done():
		t.Fatal("контекст отменён до отправки команды")
	}

	// Проверяем, что канал приёма карт освободился штатно: если бы
	// подписка сломалась, список карт уходил бы в никуда.
	select {
	case <-cardsCh:
		t.Log("получен список карт от контроллера")
	default:
		t.Log("список карт ещё не пришёл — придёт следующим обращением контроллера")
	}

	// Дальше контроллер пришлёт список отдельным обращением — это уже
	// проверяется в тесте в пакете service, где есть HTTP-обработчик.
	t.Log("команда ушла; список придёт следующим обращением контроллера")
}
