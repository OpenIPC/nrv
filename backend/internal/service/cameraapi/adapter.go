// Package cameraapi — единый доступ к устройствам разных производителей.
//
// Задача: дать системе возможность читать состояние камеры и управлять ею
// независимо от того, чей это производитель. До появления этого пакета
// система умела только определять производителя и скрывать от чужих камер
// разделы OpenIPC — то есть не умела с ними работать вовсе.
//
// Устройство пакета — два слоя, и это главное его решение.
//
//   - Общий слой — ONVIF. Это один язык для большинства производителей:
//     проверено на живых Vivotek и Beward, тот же протокол используется
//     камерами Dahua, Axis, Uniview. Один код вместо отдельного клиента под
//     каждый бренд.
//
//   - Вендорский слой — там, где общий язык не работает или беднее. Так
//     вышло с Hikvision: по ONVIF её камера требует ONVIF-пользователя,
//     которого на устройстве нет, а фирменный ISAPI работает сразу и
//     отдаёт больше — состояние процессора и памяти, параметры потоков,
//     карту памяти.
//
// Выбор между слоями — не догадка интерфейса, а решение, принятое по факту
// опроса: см. Manager.
package cameraapi

import (
	"context"
	"errors"
	"time"

	"github.com/nvr/backend/internal/domain"
)

// Ошибки, которые важно различать вызывающему коду.
var (
	// ErrNotSupported — производитель не поддержан ни одним из адаптеров.
	//
	// Не ошибка связи и не сбой: устройство может быть полностью исправно,
	// просто мы не знаем, как к нему обращаться. Оператору такие случаи
	// нужно показывать по-разному.
	ErrNotSupported = errors.New("для этого производителя нет доступа по API")
	// ErrAuthFailed — устройство отклонило учётные данные.
	ErrAuthFailed = errors.New("устройство отклонило учётные данные")
	// ErrUnreachable — устройство не ответило.
	ErrUnreachable = errors.New("устройство не ответило")
	// ErrMethodNotAllowed — устройство ответило, но операцию не разрешает.
	// Например, перезагрузка недоступна пользователю с такими правами.
	ErrMethodNotAllowed = errors.New("устройство не разрешает эту операцию")
)

// DeviceInfo — сведения об устройстве.
type DeviceInfo struct {
	Manufacturer string `json:"manufacturer"`
	Model        string `json:"model"`
	Firmware     string `json:"firmware"`
	// FirmwareDate — дата сборки прошивки, если устройство её сообщает.
	FirmwareDate string `json:"firmware_date,omitempty"`
	Serial       string `json:"serial,omitempty"`
	HardwareID   string `json:"hardware_id,omitempty"`
	MAC          string `json:"mac,omitempty"`
	// DeviceType — «IPCamera», «IPDome» и подобное: производитель называет
	// вид устройства сам.
	DeviceType string `json:"device_type,omitempty"`

	// Source — откуда получены сведения: "isapi" или "onvif".
	//
	// Показывается оператору не ради любопытства: набор доступных действий
	// зависит от источника, и при разборе непонятного поведения важно
	// знать, через что мы разговаривали с камерой.
	Source string `json:"source"`
}

// DeviceStatus — текущее состояние устройства.
type DeviceStatus struct {
	// UptimeSeconds — время работы с последней загрузки.
	//
	// Самая полезная величина из всех: по ней видно, перезагружалась ли
	// камера, и она же подтверждает, что перезагрузка действительно
	// произошла, — в отличие от кода ответа, который лишь сообщает, что
	// команда принята.
	UptimeSeconds int64 `json:"uptime_seconds"`
	// DeviceTime — часы устройства. Расходятся с нашими, если камера
	// ходит за временем не туда.
	//
	// Указатель, а не значение. Часы читаются отдельным запросом, и он
	// может не пройти: устройство отдаёт сведения о себе, но молчит про
	// время. Значение времени в этом случае осталось бы нулевым, и
	// карточка показала бы «01.01.1» — то есть выдуманную дату вместо
	// честного «не прочитано». Проверено на живом домофоне Beward.
	DeviceTime *time.Time `json:"device_time,omitempty"`
	// TimeDriftSeconds — расхождение часов устройства с сервером.
	//
	// Знак задан так: положительное значение означает, что часы устройства
	// ОТСТАЮТ — оно показывает время в прошлом. Так получилось потому, что
	// величина считается как время, прошедшее от показаний устройства до
	// наших часов. На живых камерах парка встречается отставание в 139
	// суток; при обратном толковании знака оператор перевёл бы часы не в ту
	// сторону, поэтому направление здесь описано, а не подразумевается.
	//
	// Указатель по той же причине, что и у времени: ноль здесь означал бы
	// «часы точны», а это утверждение, а не отсутствие данных. Показать
	// «точно» там, где часы не прочитаны, — хуже, чем не показать ничего.
	TimeDriftSeconds *int64 `json:"time_drift_seconds,omitempty"`

	CPUPercent    float64 `json:"cpu_percent,omitempty"`
	MemoryPercent float64 `json:"memory_percent,omitempty"`
	MemoryFreeKB  int64   `json:"memory_free_kb,omitempty"`
}

// SetClock записывает часы устройства и считает расхождение с нашими.
//
// Вынесено в один метод, потому что расчёт есть у каждого способа
// обращения, а знак величины — общий для всех. Три копии одного расчёта
// разошлись бы, и на одной из марок расхождение показывалось бы с обратным
// знаком. Нулевое время означает, что часы прочитать не удалось: тогда
// ничего не записывается, и в ответе поля просто отсутствуют.
func (s *DeviceStatus) SetClock(t time.Time) {
	if t.IsZero() {
		return
	}
	drift := int64(time.Since(t).Seconds())
	s.DeviceTime = &t
	s.TimeDriftSeconds = &drift
}

// StreamInfo — параметры одного потока.
type StreamInfo struct {
	// ID — идентификатор канала устройства: «101» — основной поток,
	// «102» — дополнительный. Нумерация общая у Hikvision и в ONVIF.
	ID   string `json:"id"`
	Name string `json:"name,omitempty"`

	Codec  string  `json:"codec,omitempty"`
	Width  int     `json:"width,omitempty"`
	Height int     `json:"height,omitempty"`
	FPS    float64 `json:"fps,omitempty"`

	// RateControl — способ управления битрейтом: CBR или VBR.
	RateControl string `json:"rate_control,omitempty"`
	// BitrateKbps — целевой битрейт. Для VBR это верхняя граница.
	BitrateKbps int `json:"bitrate_kbps,omitempty"`
}

// Adapter — доступ к устройству.
//
// В интерфейс входят только чтение и только то, что умеют все: сведения об
// устройстве и состояние. Всё остальное вынесено в отдельные интерфейсы
// ниже.
//
// Это не формальность. Камера, которая не умеет перезагружаться, не должна
// считаться неисправной и не должна ломать карточку — а именно это
// произошло бы, если бы перезагрузка входила в общий интерфейс. Такой же
// приём уже применён в подсистеме СКУД: интерфейс CardManager вынесен из
// общего Adapter по той же причине.
type Adapter interface {
	// Info возвращает сведения об устройстве.
	Info(ctx context.Context) (*DeviceInfo, error)
	// Status возвращает текущее состояние.
	Status(ctx context.Context) (*DeviceStatus, error)
	// Name возвращает название адаптера для журнала и диагностики.
	Name() string
}

// Rebooter умеет перезагружать устройство.
//
// Отдельный интерфейс, потому что перезагрузка — действие разрушительное:
// камера уходит из сети на минуту с лишним. Не все устройства её
// разрешают, и не для всех моделей она проверена.
type Rebooter interface {
	Reboot(ctx context.Context) error
}

// StreamReader умеет читать параметры потоков.
type StreamReader interface {
	Streams(ctx context.Context) ([]StreamInfo, error)
}

// Target — устройство, к которому обращается адаптер.
//
// Отдельный тип, а не domain.Camera: адаптерам нужны только адрес и
// учётные данные, и передавать им всю карточку значило бы позволить им
// читать и менять то, к чему они не имеют отношения.
type Target struct {
	IP       string
	Username string
	Password string
	// Vendor — производитель, определённый системой. От него зависит
	// выбор адаптера.
	Vendor domain.Vendor
}

// Account достаёт учётные данные камеры из её настроек.
//
// Возвращает пустые строки, если их нет: адаптеры сами решают, пробовать
// ли запрос без авторизации. Часть устройств отвечает и так.
func Account(cam *domain.Camera) (string, string) {
	if cam == nil || cam.Settings == nil {
		return "", ""
	}
	u, _ := cam.Settings["username"].(string)
	p, _ := cam.Settings["password"].(string)
	return u, p
}

// TargetFor собирает адрес устройства и учётные данные из карточки камеры.
func TargetFor(cam *domain.Camera) Target {
	user, pass := Account(cam)
	return Target{
		IP:       cam.IP,
		Username: user,
		Password: pass,
		Vendor:   domain.ResolveVendor(cam),
	}
}
