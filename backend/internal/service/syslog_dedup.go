package service

import (
	"github.com/nvr/backend/internal/domain"
	"sync"
	"time"
)

// Дедупликация syslog-строк.
//
// Зачем: одна сломавшаяся камера выдаёт одну и ту же ошибку в цикле —
// десятки раз в минуту. Без отсева такая камера забивает таблицу логов
// и вытесняет из неё сообщения остальных устройств. Разбирать логи, где
// 99% строк одинаковы, невозможно.
//
// Как: одинаковые строки (один отпечаток) внутри окна считаются повтором,
// а не новой записью. Повторы не пропадают бесследно — их число можно
// показать, и по нему видно, что проблема повторяется.
//
// Почему окно по времени, а не «запомнить навсегда»: ошибка может
// исчезнуть и вернуться через час, и это уже другое событие, о котором
// нужно сообщить заново. Вечное залипание скрыло бы возврат проблемы.

// syslogDedupWindow — в течение какого времени одинаковые строки
// считаются повтором. Минуты достаточно: циклы в камерах повторяются
// чаще, а настоящие редкие события в минуту не укладываются.
const syslogDedupWindow = time.Minute

// syslogDedupMaxKeys — предел числа запомненных отпечатков.
//
// Ограничение обязательно: камера с новой ошибкой каждую секунду создавала
// бы новые отпечатки, и карта росла бы без предела. При достижении порога
// карта очищается целиком, а не вытесняет по одному: точность окна в этот
// момент всё равно уже потеряна, а полная очистка дешевле и проще, чем
// учёт порядка использования.
const syslogDedupMaxKeys = 20000

type syslogDedup struct {
	mu     sync.Mutex
	seenAt map[string]time.Time
	// now вынесено в поле, чтобы тест мог управлять временем без ожидания.
	now func() time.Time
}

func newSyslogDedup() *syslogDedup {
	return &syslogDedup{
		seenAt: make(map[string]time.Time),
		now:    time.Now,
	}
}

// seen сообщает, является ли строка повтором, и запоминает её.
func (d *syslogDedup) seen(entry domain.SyslogEntry) bool {
	key := entry.Fingerprint
	// Без отпечатка дедуплицировать нечего: считаем строку уникальной,
	// чтобы не потерять её.
	if key == "" {
		return false
	}

	d.mu.Lock()
	defer d.mu.Unlock()

	now := d.now()

	if prev, ok := d.seenAt[key]; ok && now.Sub(prev) < syslogDedupWindow {
		// Повтор: время не обновляем. Иначе беспрерывно повторяющаяся
		// ошибка продлевала бы окно бесконечно, и о её возврате через
		// час уже не было бы сообщения.
		return true
	}

	if len(d.seenAt) >= syslogDedupMaxKeys {
		d.seenAt = make(map[string]time.Time)
	}
	d.seenAt[key] = now

	// Заодно подчищаем устаревшие записи: иначе карта заполнится старыми
	// отпечатками и будет очищаться целиком чаще, чем нужно.
	d.pruneLocked(now)

	return false
}

// pruneLocked удаляет отпечатки старше окна. Вызывается под замком.
func (d *syslogDedup) pruneLocked(now time.Time) {
	// Проход по всей карте на каждой вставке был бы дорог, поэтому
	// подчищаем редко — примерно раз в сотню новых отпечатков.
	// Ведём счётчик через остаток от длины: это дешевле отдельного поля.
	if len(d.seenAt)%100 != 0 {
		return
	}
	for key, at := range d.seenAt {
		if now.Sub(at) >= syslogDedupWindow {
			delete(d.seenAt, key)
		}
	}
}

// size — число запомненных отпечатков. Нужно тестам.
func (d *syslogDedup) size() int {
	d.mu.Lock()
	defer d.mu.Unlock()
	return len(d.seenAt)
}
