// Package sscpoe — протокол управляемых PoE-коммутаторов SSCPOE.
//
// Протокол восстановлен по поведению живых устройств (PS204, GPS204V3) и
// проверен на них же. Документации производитель не публикует, поэтому
// все константы и форматы здесь подтверждены запросами к работающему
// оборудованию, а не взяты из описания.
//
// Из трёх найденных каналов связи реализован только локальный (UDP):
//
//   - облако — требует регистрации на сайте производителя и интернета;
//   - веб — требует HTTP-доступа к устройству, который на живых
//     коммутаторах оказался закрыт либо обрывал соединение;
//   - локальный UDP — работает всегда, потому что встроен в устройство
//     для его собственного поиска в сети, и не требует ни пароля, ни
//     веб-интерфейса.
//
// Выбор сделан по факту: веб-интерфейс на проверенных коммутаторах
// недоступен, а UDP-канал ответил сразу и без аутентификации.
package sscpoe

