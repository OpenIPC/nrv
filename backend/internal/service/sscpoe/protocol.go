// MacEntry — одна запись таблицы MAC-адресов.
type MacEntry struct {
	// MAC — адрес без разделителей, в нижнем регистре.
	MAC string
	// PortIndexes — внутренние индексы портов, через которые доступен
	// адрес. Пусто, если устройство не сообщило порт.
	//
	// Индекс — позиция в массивах состояния, а не номер порта на корпусе.
	// Перевод делает LabelPort: у части моделей порты PoE пронумерованы
	// в обратном порядке.
	PortIndexes []int
}

// MacTable — таблица MAC-адресов коммутатора.
type MacTable struct {
	Entries []MacEntry
	// UniformBitmap — у всех записей одинаковая маска портов.
	//
	// Так ведёт себя часть прошивок: поле заполняется одним значением на
	// все записи, и по нему нельзя понять, к какому порту подключено
	// устройство. Проверено на живом PS208GV3: 30 записей и одно значение
	// 512 для всех, включая устройства на собственных PoE-портах. Признак
	// вычисляется здесь, потому что описывает свойство самой таблицы, а не
	// решение вызывающего кода.
	UniformBitmap bool
	// Empty — таблица не содержит пригодных записей.
	Empty bool
}

// macTableRaw — таблица в том виде, в каком её отдаёт устройство.
//
// Массивы параллельны: элемент i относится к одной записи. Поле bitmap
// несёт маску портов, fwd и sign в работе не используются, но оставлены
// в разборе: они приходят всегда, и их отсутствие — признак того, что
// формат изменился.
type macTableRaw struct {
	// Указатель, а не срез: так отличаем «поля нет вовсе» от «поле есть,
	// но таблица пуста». Первое означает, что разбор не туда попал, и это
	// ошибка; второе — законное состояние коммутатора без устройств.
	MAC    *[]string `json:"MAC"`
	Bitmap []int     `json:"bitmap"`
	Fwd    []int     `json:"fwd"`
	Sign   []int     `json:"sign"`
}

// ParseMacTable разбирает ответ с таблицей MAC-адресов.
//
// Ответ обёрнут так же, как состояние портов: данные лежат внутри поля
// calldata, а само оно бывает и объектом, и строкой с JSON внутри. Без
// разбора обёртки таблица выглядела бы пустой при полностью исправной
// связи — именно на этом и была ошибка в первой версии.
func ParseMacTable(data json.RawMessage) (*MacTable, error) {
	// Сообщение вместо данных означает требование входа, а не сбой.
	if isJSONString(data) {
		var msg string
		if err := json.Unmarshal(data, &msg); err != nil {
			return nil, fmt.Errorf("не удалось прочитать сообщение устройства: %w", err)
		}
		return nil, &DeviceMessageError{Message: msg}
	}

	var mid struct {
		CallData json.RawMessage `json:"calldata"`
	}
	if err := json.Unmarshal(data, &mid); err != nil {
		return nil, fmt.Errorf("неожиданный формат ответа: %w", err)
	}

	payload, err := unwrapData(mid.CallData)
	if err != nil {
		return nil, err
	}

	var t macTableRaw
	if err := json.Unmarshal(payload, &t); err != nil {
		return nil, fmt.Errorf("не удалось разобрать таблицу MAC: %w", err)
	}
	if t.MAC == nil {
		return nil, fmt.Errorf("в ответе нет поля MAC: формат ответа изменился")
	}

	tbl := &MacTable{Empty: len(*t.MAC) == 0}
	seen := map[string]bool{}
	bitmaps := map[int]bool{}

	for i, mac := range *t.MAC {
		// Приводим адрес к сравнимому виду сразу: устройство отдаёт его
		// без разделителей, а в базе камер он хранится с двоеточиями.
		// Без приведения совпадений не нашлось бы вовсе, и привязка камер
		// к портам не работала бы никогда.
		m := NormalizeMAC(mac)
		if m == "" || seen[m] {
			continue
		}
		seen[m] = true

		e := MacEntry{MAC: m}
		if i < len(t.Bitmap) {
			bitmaps[t.Bitmap[i]] = true
			e.PortIndexes = BitsToPorts(t.Bitmap[i])
		}
		tbl.Entries = append(tbl.Entries, e)
	}

	tbl.Empty = len(tbl.Entries) == 0
	// Одинаковая маска у нескольких записей означает, что поле не несёт
	// информации о порте. Для одной записи такой вывод сделать нельзя:
	// у коммутатора с одним подключённым устройством маска тоже одна.
	tbl.UniformBitmap = len(bitmaps) <= 1 && len(tbl.Entries) > 1
	return tbl, nil
}

// BitsToPorts разбирает маску в список внутренних индексов портов.
//
// Маска битовая: бит N означает порт с индексом N. Число битов равно
// числу портов устройства — сначала идут порты PoE, затем транзитные,
// поэтому отсечение лишних битов делает вызывающий код, знающий состав
// портов модели.
//
// Верхняя граница 32 нужна только как страховка от мусора в ответе:
// столько битов покрывают любое встреченное число портов.
func BitsToPorts(bitmap int) []int {
	ports := make([]int, 0, 4)
	for i := 0; i < 32; i++ {
		if bitmap&(1<<uint(i)) != 0 {
			ports = append(ports, i)
		}
	}
	return ports
}

// NormalizeMAC приводит адрес к виду без разделителей в нижнем регистре.
//
// Возвращает пустую строку, если значение не похоже на MAC: тогда запись
// отбрасывается целиком. Сопоставлять по обрывку нельзя — можно привязать
// камеру к чужому порту.
func NormalizeMAC(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= '0' && c <= '9', c >= 'a' && c <= 'f':
			b.WriteByte(c)
		case c >= 'A' && c <= 'F':
			b.WriteByte(c + ('a' - 'A'))
		}
	}

	// Полный MAC — ровно 12 шестнадцатеричных знаков.
	out := b.String()
	if len(out) != 12 {
		return ""
	}
	return out
}

// parseNumber разбирает число из строки, возвращая 0 при неудаче.
// ParseNumber разбирает число из строки, возвращая 0 при неудаче.
//
// Экспортируется, потому что тем же разбором пользуется сервисный слой:
// часть значений приходит строками с десятичной точкой, и дублировать
// разбор в двух местах означало бы получить два разных поведения на
// некорректных данных.
func ParseNumber(s string) float64 {
	s = strings.TrimSpace(s)
	if s == "" {
		return 0
	}
	v, err := strconv.ParseFloat(s, 64)
	if err != nil {
		return 0
	}
	return v
}

// Encrypt кодирует данные в формат, который понимает коммутатор.
//
// Схема: строку JSON шифруем блочным алгоритмом (8 байт за раз), остаток
// добираем побайтовой подстановкой, результат кодируем base64. Полученная
// строка уходит в UDP-пакете.
func Encrypt(plain []byte) string {
	out := make([]byte, len(plain))
	keys := keyWords(localKey)

	// Целые блоки по 8 байт.
	whole := len(plain) - len(plain)%8
	for off := 0; off < whole; off += 8 {
		var block [8]byte
		copy(block[:], plain[off:off+8])
		enc := encryptBlock(block, keys)
		copy(out[off:off+8], enc[:])
	}

	// Хвост короче 8 байт: блочный алгоритм к нему неприменим, поэтому
	// каждый байт смещается отдельно, с учётом его позиции. Это часть
	// формата: коммутатор разбирает хвост так же.
	for i := whole; i < len(plain); i++ {
		out[i] = encryptByte(plain[i], keys, i)
	}

	return base64.StdEncoding.EncodeToString(out)
}

// Decrypt разбирает ответ коммутатора.
//
// Порядок обратный Encrypt. Ошибка декодирования base64 означает, что
// ответ не от этого протокола, а расхождение после расшифровки — что
// ответ предназначен другому запросу; отличать эти случаи важно, чтобы
// не принять чужой пакет за состояние своего коммутатора.
func Decrypt(encoded string, key []byte) ([]byte, error) {
	raw, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return nil, fmt.Errorf("ответ не в формате протокола: %w", err)
	}
	if len(key) != 16 {
		return nil, fmt.Errorf("ключ должен быть длиной 16 байт, получено %d", len(key))
	}

	out := make([]byte, len(raw))
	keys := keyWords(key)

	whole := len(raw) - len(raw)%8
	for off := 0; off < whole; off += 8 {
		var block [8]byte
		copy(block[:], raw[off:off+8])
		dec := decryptBlock(block, keys)
		copy(out[off:off+8], dec[:])
	}
	for i := whole; i < len(raw); i++ {
		out[i] = decryptByte(raw[i], keys, i)
	}
	return out, nil
}

// keyWords переводит 16-байтовый ключ в четыре 32-битных слова: так его
// использует блочный алгоритм.
func keyWords(key []byte) [4]uint32 {
	var w [4]uint32
	for i := 0; i < 4; i++ {
		w[i] = uint32(key[i*4]) | uint32(key[i*4+1])<<8 |
			uint32(key[i*4+2])<<16 | uint32(key[i*4+3])<<24
	}
	return w
}

// encryptBlock шифрует один 8-байтовый блок.
//
// Раунды идут в прямом порядке; DELTA прибавляется до вычисления, поэтому
// при расшифровке то же значение вычитается после. Перестановка этих
// операций даёт нечитаемый результат — это не ошибка округления, а
// нарушение алгоритма.
func encryptBlock(v [8]byte, k [4]uint32) [8]byte {
	v0 := uint32(v[0]) | uint32(v[1])<<8 | uint32(v[2])<<16 | uint32(v[3])<<24
	v1 := uint32(v[4]) | uint32(v[5])<<8 | uint32(v[6])<<16 | uint32(v[7])<<24

	var sum uint32
	for i := 0; i < teaRounds; i++ {
		sum += teaDelta
		v0 += ((v1 << 4) + k[0]) ^ (v1 + sum) ^ ((v1 >> 5) + k[1])
		v1 += ((v0 << 4) + k[2]) ^ (v0 + sum) ^ ((v0 >> 5) + k[3])
	}

	var out [8]byte
	out[0], out[1], out[2], out[3] = byte(v0), byte(v0>>8), byte(v0>>16), byte(v0>>24)
	out[4], out[5], out[6], out[7] = byte(v1), byte(v1>>8), byte(v1>>16), byte(v1>>24)
	return out
}

// decryptBlock расшифровывает один 8-байтовый блок.
func decryptBlock(v [8]byte, k [4]uint32) [8]byte {
	v0 := uint32(v[0]) | uint32(v[1])<<8 | uint32(v[2])<<16 | uint32(v[3])<<24
	v1 := uint32(v[4]) | uint32(v[5])<<8 | uint32(v[6])<<16 | uint32(v[7])<<24

	// Начальное значение суммы равно числу раундов, умноженному на DELTA.
	// Считаем накоплением, а не умножением: множитель переполняет 32 бита,
	// и компилятор отвергает такое выражение целиком. Накопление даёт тот
	// же результат заведомо корректной разрядности.
	var sum uint32
	for i := 0; i < teaRounds; i++ {
		sum += teaDelta
	}
	for i := 0; i < teaRounds; i++ {
		v1 -= ((v0 << 4) + k[2]) ^ (v0 + sum) ^ ((v0 >> 5) + k[3])
		v0 -= ((v1 << 4) + k[0]) ^ (v1 + sum) ^ ((v1 >> 5) + k[1])
		sum -= teaDelta
	}

	var out [8]byte
	out[0], out[1], out[2], out[3] = byte(v0), byte(v0>>8), byte(v0>>16), byte(v0>>24)
	out[4], out[5], out[6], out[7] = byte(v1), byte(v1>>8), byte(v1>>16), byte(v1>>24)
	return out
}

// encryptByte обрабатывает один байт хвоста. Позиция байта важна: от неё
// зависят подставляемые значения, поэтому одинаковые байты в разных
// местах шифруются по-разному.
func encryptByte(b byte, k [4]uint32, index int) byte {
	m := byteSalt[index%8]
	kk := k[index%4]
	s := uint32(b)
	for i := 0; i < teaRounds; i++ {
		s += (uint32(m)<<2 + kk) ^ (uint32(m)>>3 + kk)
	}
	return byte(s)
}

// decryptByte снимает обработку одного байта хвоста.
func decryptByte(b byte, k [4]uint32, index int) byte {
	m := byteSalt[index%8]
	kk := k[index%4]
	s := uint32(b)
	for i := 0; i < teaRounds; i++ {
		s -= (uint32(m)<<2 + kk) ^ (uint32(m)>>3 + kk)
	}
	return byte(s)
}

// EncodeRequest собирает строку запроса для отправки в UDP-пакет.
//
// Формат конверта — часть протокола: внутри data лежит сам запрос, а поле
// cmd сообщает устройству, что пакет адресован ему. syn — случайный
// маркер, по которому мы отличим ответ на свой запрос от чужого: в
// мультикасте видны устройства всей подсети, и без сверки маркера мы
// приняли бы состояние соседнего коммутатора за состояние своего.
func EncodeRequest(req Request, syn string) (string, error) {
	inner, err := json.Marshal(req)
	if err != nil {
		return "", fmt.Errorf("не удалось собрать запрос: %w", err)
	}

	// Границы здесь не декорация: если брать inner как json.RawMessage,
	// он подставится сырым. Нам нужен именно вложенный объект, поэтому
	// оборачиваем его готовой строкой.
	envelope := struct {
		Cmd  string         `json:"cmd"`
		Syn  string         `json:"syn"`
		Data map[string]any `json:"data"`
	}{Cmd: callUDPCmd, Syn: syn}

	if err := json.Unmarshal(inner, &envelope.Data); err != nil {
		return "", fmt.Errorf("не удалось подготовить запрос: %w", err)
	}

	buf, err := json.Marshal(envelope)
	if err != nil {
		return "", fmt.Errorf("не удалось упаковать запрос: %w", err)
	}
	return Encrypt(buf), nil
}

// ResponseEnvelope — конверт ответа устройства.
//
// Ack подтверждает, что это ответ на calludp, syn связывает ответ с
// запросом, errcode несёт код ошибки устройства (0 — успех).
type ResponseEnvelope struct {
	Ack     string          `json:"ack"`
	Syn     string          `json:"syn"`
	ErrCode int             `json:"errcode"`
	Data    json.RawMessage `json:"data"`
}

// DecodeResponse разбирает ответ и проверяет, что он относится к нашему
// запросу.
func DecodeResponse(payload []byte, syn string, key []byte) (*ResponseEnvelope, error) {
	// Ответ приходит с завершающим переводом строки — он отделяет одно
	// сообщение от другого в потоке UDP.
	trimmed := bytes.TrimRight(payload, "\r\n")

	plain, err := Decrypt(string(trimmed), key)
	if err != nil {
		return nil, err
	}

	var env ResponseEnvelope
	if err := json.Unmarshal(plain, &env); err != nil {
		return nil, fmt.Errorf("ответ не является JSON: %w", err)
	}
	if env.Ack != callUDPCmd {
		return nil, fmt.Errorf("ответ не относится к протоколу: ack=%q", env.Ack)
	}
	if env.Syn != syn {
		return nil, fmt.Errorf("ответ на другой запрос: syn=%q, ожидался %q", env.Syn, syn)
	}
	return &env, nil
}

// callUDPCmd — значение поля cmd в конверте. Сообщает устройству, что
// пакет является запросом по локальному протоколу.
const callUDPCmd = "calludp"
