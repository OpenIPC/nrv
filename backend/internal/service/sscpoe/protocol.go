// Request — запрос к коммутатору.
//
// CallCmd определяет операцию; остальные поля заполняются в зависимости
// от неё. Набор строковый, а не числовой: так его использует само
// устройство, и числовые коды в разных прошивках могут сдвигаться.
//
// Внимание к расположению полей: у разных операций они лежат на разной
// глубине, и это не вольность формата, а требование устройства:
//
//   - detail и config кладут свои параметры во вложенный объект calldata;
//   - проверка пароля принимает password и command на верхнем уровне и
//     вложенный объект игнорирует целиком.
//
// Ошибка здесь не даёт видимой причины отказа: устройство просто не
// отвечает, и это легко принять за неисправность сети. Проверено на
// живом GPS204V3: с вложенным паролем — таймаут, с плоским — успех.
type Request struct {
	// CallCmd — имя или числовой код операции.
	//
	// Тип допускает оба вида, и это не небрежность: устройство называет
	// высокоуровневые операции строкой ("detail", "config"), а команды,
	// повторяющие веб-интерфейс, — числом (114 — таблица MAC). Приводить
	// одно к другому нельзя: неизвестно, понимает ли устройство строковую
	// форму для числовых команд, а проверять это наугад нельзя: среди
	// кодов есть сброс к заводским настройкам.
	CallCmd  any            `json:"callcmd"`
	SN       string         `json:"sn,omitempty"`
	CallData map[string]any `json:"calldata,omitempty"`

	// Password и Command нужны только для проверки пароля и передаются на
	// верхнем уровне — так их ждёт устройство.
	Password string `json:"password,omitempty"`
	Command  string `json:"command,omitempty"`
}

// DeviceInfo — краткие сведения об устройстве из ответа на поиск.
type DeviceInfo struct {
	SN    string `json:"sn"`
	IP    string `json:"ip"`
	MAC   string `json:"mac"`
	Model string `json:"model"`
	// ActiveState присутствует не во всех прошивках. Пустое значение
	// трактуется как «активно»: устройство ответило на поиск, значит оно
	// в сети и работает.
	ActiveState string `json:"Active_state,omitempty"`
}

// Detail — состояние коммутатора, отдаваемое на запрос detail.
//
// Массивы параллельны: элемент i относится к порту i, но нумерация портов
// может быть обратной — см. domain.Switch.PortsReversed. Смешивать индекс
// массива и номер порта нельзя, это приводит к командам не на тот порт.
type Detail struct {
	SN *string `json:"sn,omitempty"`
	IP string  `json:"ip"`
	// V — версия прошивки, vol — напряжение питания.
	V   string `json:"V"`
	Vol string `json:"vol"`
	MAC string `json:"mac"`

	// T — температура в градусах. Имя поля пришло с GPS204V3.
	//
	// Про tp: на PS204 в нём лежит температура (13.0), а на GPS204V3 —
	// значение 9100, то есть мусор. Единого поля нет, и выбирать нужно
	// по содержимому, а не по имени. Разбор делает Temperature().
	T  string `json:"T,omitempty"`
	Tp string `json:"tp,omitempty"`

	// PW — потребляемая портом мощность в ваттах (PoE). Значения приходят
	// строками и содержат десятичную точку.
	//
	// Длина массива равна числу PoE-портов и может быть МЕНЬШЕ общего
	// числа портов: на GPS204V3 портов шесть, а PoE только на четырёх.
	// Индекс здесь — индекс PoE-порта, и он совпадает с индексом в
	// массивах Link и PhyC.
	PW []string `json:"pw"`
	// Link — наличие связи: 0 — связи нет, ненулевое — связь есть.
	// Длина равна общему числу портов.
	Link []int `json:"link"`
	// Tx и Rx — объём переданного и принятого трафика, МБ.
	Tx []string `json:"tx"`
	Rx []string `json:"rx"`
	// SNR — соотношение сигнал/шум для линий с удлинением.
	SNR []int `json:"snr"`
	// PoeC — управление питанием: 1 — включено, 0 — выключено. Длина та
	// же, что у PW: только PoE-порты.
	//
	// Именно это значение меняется командой, и именно оно показывается.
	PoeC []int `json:"poec"`
	// PhyC — режим порта и скорость. Длина равна общему числу портов.
	PhyC []int `json:"phyc"`
	// Uplink — битовая маска транзитных портов. Установленный бит i
	// означает, что порт с индексом i является восходящим каналом.
	//
	// Значение нужно, чтобы не пытаться управлять питанием на транзитном
	// порту: оно там не отдаётся, и команда бессмысленна. На GPS204V3
	// значение 16 = 2^4 указывает на индекс 4 — порт, к которому
	// подключён модем.
	Uplink *int `json:"uplink,omitempty"`
	// Isoc — изоляция портов друг от друга.
	Isoc *int `json:"isoc,omitempty"`
	// AdminState — административное состояние портов.
	AdminState []int `json:"AdminState,omitempty"`
}

// PortCount возвращает общее число портов.
//
// Считаем по массиву линков, а не по максимальной длине всех массивов:
// массив потребления короче, потому что содержит только PoE-порты, и
// опора на него занизила бы число портов — пятый порт с модемом пропал бы
// из интерфейса. Опора на максимум, наоборот, показала бы четыре порта как
// шесть с пустыми полями питания.
func (d *Detail) PortCount() int {
	n := len(d.Link)
	if l := len(d.PhyC); l > n {
		n = l
	}
	if l := len(d.AdminState); l > n {
		n = l
	}
	return n
}

// PoECount возвращает число портов с поддержкой PoE.
//
// Именно эти порты accepting команды питания. Нумерация портов для
// оператора начинается с единицы и не выходит за это число.
func (d *Detail) PoECount() int {
	return len(d.PoeC)
}

// Temperature возвращает температуру в градусах, ноль — если определить
// не удалось.
//
// Единого поля нет, и это выяснено на живых устройствах:
//
//   - PS204 кладёт температуру в tp (13.0), а поле T не присылает вовсе;
//   - GPS204V3 кладёт температуру в T (20.5), а в tp — мусор 9100.
//
// Порядок перебора намеренно начинается с tp, потому что на модели, где
// поле T отсутствует, это единственный источник. Если же в tp лежит
// значение, не похожее на температуру, берём T. Обратный порядок давал бы
// ровно ноль на PS204 — и оператор не увидел бы температуру там, где она
// есть.
func (d *Detail) Temperature() float64 {
	if t, ok := plausibleTemp(d.Tp); ok {
		return t
	}
	if t, ok := plausibleTemp(d.T); ok {
		return t
	}
	return 0
}

// plausibleTemp разбирает значение и проверяет его правдоподобность.
//
// Порог ±60 °C взят с запасом относительно реальных условий: коммутатор
// работает в помещении или щите, и выход за эти пределы означает либо
// неисправность датчика, либо что в поле лежит не температура. Проверка
// нужна ради моделей, кладущих в поле посторонние числа: показать
// оператору 9100 °C хуже, чем не показать ничего.
func plausibleTemp(s string) (float64, bool) {
	if strings.TrimSpace(s) == "" {
		return 0, false
	}
	v := ParseNumber(s)
	if v < -60 || v > 60 {
		return 0, false
	}
	return v, true
}

// isUplink сообщает, является ли порт с данным индексом транзитным.
//
// Определяется по битовой маске: установленный бит с номером, равным
// индексу порта, означает восходящий канал. Через такое поле удобно
// помечать любое число портов сразу.
func (d *Detail) isUplink(index int) bool {
	if d.Uplink == nil || index < 0 || index > 31 {
		return false
	}
	return *d.Uplink&(1<<uint(index)) != 0
}

// IsUplink — экспортируемая проверка для вызывающего кода.
func (d *Detail) IsUplink(index int) bool {
	return d.isUplink(index)
}

