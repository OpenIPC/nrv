// Команды протокола.
const (
	// CmdSearch — широковещательный поиск. Отвечают все коммутаторы.
	CmdSearch = "search"
	// CmdDetail — состояние коммутатора: порты, питание, температура.
	CmdDetail = "detail"
	// CmdConfig — изменение состояния порта.
	CmdConfig = "config"
	// CmdMacTable — таблица MAC-адресов: какие устройства видит коммутатор.
	//
	// Номер команды найден в карте операций веб-интерфейса самого
	// устройства (mac_table: 114), а не подбором. Подбор здесь был бы
	// опасен: среди кодов есть операции вроде сброса к заводским
	// настройкам, и попасть на них случайно нельзя.
	//
	// Числовой код, а не строковый: так операцию называет само устройство,
	// и строковой формы для неё не существует.
	CmdMacTable = 114
	// CmdVerify — проверка пароля (вход). Значение подтверждено на
	// GPS204V3: без него устройство отвечает текстом с требованием
	// выполнить проверку, а с ним отдаёт состояние.
	CmdVerify = "Security verification"
)

// Биты управляющего кода.
//
// Формат кодов определён прошивкой и на разных моделях различается не
// полностью: часть значений совпадает, часть отличается. Поэтому коды
// собраны здесь, а не разбросаны по коду вызовов, и каждый подтверждён на
// живом устройстве.
//
// Младшие биты задают действие, старшие — индекс порта (сдвиг на 4).
// Разделение на «младшие» и «старшие» важно: индекс сдвигается влево, а
// не прибавляется, иначе индекс 1 совпал бы с младшим битом действия.
const (
	// При управлении питанием: 0x202 — включить, 0x002 — выключить.
	// Значение подтверждено на GPS204V3: команда выключения дала poec=0 и
	// link=0, команда включения вернула питание, линк восстановился.
	opPoeOn  = 0x202
	opPoeOff = 0x002

	// При управлении длиной линии: 0x400 — включить удлинение (скорость
	// 10 Мбит полный дуплекс), 0xA00 — выключить (1 Гбит полный дуплекс).
	// Разные модели требуют разных значений: часть отвечает ошибкой 1001
	// на 0xA00 и понимает 0x800 вместо него.
	opExtendOn  = 0x400
	opExtendOff = 0xA00
	// Запасные коды для моделей, не понимающих основные. Подтверждены
	// поведением: 1001 означает «неизвестный код», после чего устройство
	// принимает альтернативный.
	opExtendOnFallback  = 0x200
	opExtendOffFallback = 0x800

	// codeUnknownOpcode — код ответа на непонятую операцию. Служит сигналом
	// попробовать запасной код: в остальных случаях повторять команду
	// нельзя, это привело бы к двойному срабатыванию действия.
	codeUnknownOpcode = 1001
)

// OpCode собирает управляющий код из действия и индекса порта.
//
// Индекс порта — это позиция в массиве ответа устройства, а не номер
// порта на корпусе. Различие принципиально: у части моделей нумерация
// обратная, и перепутать её означает выключить питание не той камеры.
// Соответствие вычисляется в PortIndex.
func OpCode(action domain.PortAction, index int) (int, error) {
	if index < 0 {
		return 0, fmt.Errorf("индекс порта не может быть отрицательным: %d", index)
	}

	var base int
	switch action {
	case domain.PortActionPowerOn:
		base = opPoeOn
	case domain.PortActionPowerOff:
		base = opPoeOff
	case domain.PortActionExtendOn:
		base = opExtendOn
	case domain.PortActionExtendOff:
		base = opExtendOff
	default:
		// Неизвестное действие не превращаем в код «по умолчанию»: под
		// этим кодом может оказаться опасная операция, например сброс
		// коммутатора к заводским настройкам.
		return 0, fmt.Errorf("неизвестное действие: %q", action)
	}
	return base | (index << 4), nil
}

// FallbackOpCode возвращает запасной код для действия и признак, что он
// существует.
//
// Только для действий удлинения: у питания альтернативного кодирования не
// найдено, и подставлять туда что-либо нельзя.
func FallbackOpCode(action domain.PortAction) (int, bool) {
	switch action {
	case domain.PortActionExtendOn:
		return opExtendOnFallback, true
	case domain.PortActionExtendOff:
		return opExtendOffFallback, true
	}
	return 0, false
}

// IsFallbackCode говорит, что ошибка устройства означает «код не понят».
//
// Нужна, чтобы повторять команду только в этом случае. Повтор при любой
// ошибке опасен: команда могла выполниться, но ответ не дойти, и повтор
// переключил бы порт второй раз.
func IsFallbackCode(err error) bool {
	return err != nil && containsCode(err, codeUnknownOpcode)
}

// containsCode проверяет наличие кода устройства в тексте ошибки.
func containsCode(err error, code int) bool {
	return err != nil && fmt.Sprintf("%d", code) != "" &&
		strings.Contains(err.Error(), fmt.Sprintf("код %d", code))
}

// PortIndex переводит номер порта на корпусе во внутренний индекс.
//
// Правило взято из веб-интерфейса самого устройства, а не выведено
// догадкой: там набор portIndex переворачивает ТОЛЬКО порты PoE, а
// транзитные оставляет на их местах в конце. Прежняя версия разворачивала
// весь список целиком, и на GPS204V3 команда, адресованная порту 1,
// попадала на внутренний индекс 5 — то есть на транзитный порт. Ошибка
// здесь означает выключение питания не той камеры, поэтому правило
// подтверждено на живой модели: на GPS204V3 portIndex = [3,2,1,0] при
// четырёх портах PoE, на PS208GV3 — [0..7], то есть без разворота.
func PortIndex(portNumber, poeCount, portCount int, reversed bool) (int, error) {
	if portNumber < 1 || portNumber > portCount {
		return 0, fmt.Errorf("порт %d вне диапазона 1..%d", portNumber, portCount)
	}
	if reversed && poeCount > 0 && portNumber <= poeCount {
		return poeCount - portNumber, nil
	}
	return portNumber - 1, nil
}

// LabelPort переводит внутренний индекс в номер порта на корпусе.
//
// Обратная к PortIndex. Переворачиваются только порты PoE: транзитные
// всегда идут последними в своём порядке, потому что на корпусе они
// и подписаны последними.
func LabelPort(index, poeCount, portCount int, reversed bool) int {
	if reversed && poeCount > 0 && index < poeCount {
		return poeCount - index
	}
	return index + 1
}

// PortsReversedFromSN определяет порядок нумерации по серийному номеру.
//
// Определение нужно только при первом добавлении коммутатора: дальше
// признак хранится в базе и правится оператором. Это принципиально —
// правило выведено по нескольким моделям парка, а не документировано
// производителем, и на новой модели оно может не сработать. Хранимое
// значение можно исправить, вычисляемое на месте — нет.
func PortsReversedFromSN(sn string) bool {
	for _, prefix := range []string{"GS1", "GPS1", "GPS2", "GFS2", "GPS4"} {
		if len(sn) >= len(prefix) && sn[:len(prefix)] == prefix {
			return true
		}
	}
	return false
}

// ModelFromSN извлекает название модели из серийного номера.
//
// Нужно, когда устройство ответило на поиск, но модель в ответе не пришла:
// у части прошивок поле пустое. Разбор основан на наблюдаемых номерах:
// модель занимает начало строки, ревизия приписывается к ней суффиксом
// (V1, V3).
//
// Логика повторяет разбор на живых устройствах: сначала берём первые
// восемь символов, и если ревизии в них нет — отбрасываем по символу,
// пока она не окажется на конце или пока не станет ясно, что строка имеет
// другой формат. Проверка «две буквы и четыре цифры» отличает серийный
// номер разбираемого вида от прочих.
//
// Если распознать не удалось, возвращается исходный номер: показать
// непонятную строку честнее, чем вывести несуществующее имя модели.
func ModelFromSN(sn string) string {
	if len(sn) < 8 {
		return sn
	}

	// Длину берём по восьми символам: модель плюс ревизия занимают ровно
	// столько на всех встреченных сериях (GPS204V3, GPS204, GS105V1).
	cut := 8
	if cut > len(sn) {
		cut = len(sn)
	}
	model := sn[:cut]

	// Ревизия может не попасть в отведённые символы, если модель короче
	// восьми знаков (GS105V1). Тогда убираем по символу справа, пока
	// ревизия не окажется на конце.
	if !hasRevisionSuffix(model) {
		if len(model) > 1 {
			model = model[:len(model)-1]
		}
		if !hasRevisionSuffix(model) {
			if len(model) > 1 {
				model = model[:len(model)-1]
			}
			// Формат «две буквы и четыре цифры» означает, что ревизии
			// нет вовсе, а лишний символ относится к серийной части.
			if isPlainModel(model) && len(model) > 1 {
				model = model[:len(model)-1]
			}
		}
	}
	return model
}

// hasRevisionSuffix сообщает, что строка заканчивается обозначением
// ревизии.
func hasRevisionSuffix(s string) bool {
	return len(s) >= 2 && (s[len(s)-2:] == "V1" || s[len(s)-2:] == "V3")
}

// isPlainModel проверяет формат «две буквы и четыре цифры».
func isPlainModel(s string) bool {
	if len(s) < 6 {
		return false
	}
	isAlpha := func(b byte) bool { return b >= 'A' && b <= 'Z' || b >= 'a' && b <= 'z' }
	isDigit := func(b byte) bool { return b >= '0' && b <= '9' }
	return isAlpha(s[0]) && isAlpha(s[1]) &&
		isDigit(s[2]) && isDigit(s[3]) && isDigit(s[4]) && isDigit(s[5])
}
