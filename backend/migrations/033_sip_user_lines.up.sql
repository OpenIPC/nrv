-- Линия SIP у учётной записи сервера.
--
-- Зачем: любому человеку, который входит в систему, нужен свой внутренний
-- номер. Без отдельной линии оператор звонил бы «с телефона вообще», и в
-- журнале вызовов было бы не видно, кто именно взял трубку. Поэтому линия
-- привязывается к пользователю и создаётся вместе с ним.
--
-- ON DELETE CASCADE выбран не случайно: без владельца линия бесполезна, а
-- оставшийся абонент занимал бы номер и путал список. Номер при этом
-- освобождается — на удалении учётной записи линия уходит вместе с ней.
ALTER TABLE sip_accounts
    ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES users(id) ON DELETE CASCADE;

-- Одна линия на учётную запись. Частичный индекс, потому что у устройств
-- (панели, камеры, трубки) владельца нет вовсе, и NULL-ы не должны
-- конфликтовать между собой.
CREATE UNIQUE INDEX IF NOT EXISTS idx_sip_accounts_user
    ON sip_accounts (user_id) WHERE user_id IS NOT NULL;
