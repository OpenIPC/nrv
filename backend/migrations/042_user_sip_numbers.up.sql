-- Закрепление внутреннего номера за учётной записью.
--
-- Зачем отдельная таблица, если номер есть в sip_accounts. Потому что линия
-- живёт своей жизнью: её правят из интерфейса, пересоздают при синхронизации
-- с Asterisk, удаляют вместе с устройством. Номер при этом терялся, и
-- человеку выдавали следующий свободный — при живой трубе, настроенной на
-- прежний номер. На практике это выглядело так: администратор входил и
-- получал 303, хотя 303 уже был у другого сотрудника, а вызовы с калитки
-- уходили не туда.
--
-- Номер — это то, что человек набирает руками и что вбито в его телефон.
-- Он должен быть свойством учётной записи, а не следствием текущего набора
-- строк в таблице абонентов.
CREATE TABLE IF NOT EXISTS user_sip_numbers (
    -- Один номер на учётную запись и одна учётная запись на номер: связь
    -- «человек ↔ номер» однозначная, иначе номер снова начнёт путаться.
    user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    number varchar(20) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Переносим уже выданные номера, чтобы закрепление началось с текущего
-- состояния, а не со следующего входа: иначе первый же вход переиграл бы
-- номера заново.
--
-- Только диапазон 3XX: он закреплён за приложениями (extensions.conf, _3XX).
-- Линии панелей и трубок с другими номерами заводятся руками и учётных
-- записей не имеют.
INSERT INTO user_sip_numbers (user_id, number)
SELECT user_id, number
FROM sip_accounts
WHERE user_id IS NOT NULL AND number LIKE '3%'
ON CONFLICT DO NOTHING;
