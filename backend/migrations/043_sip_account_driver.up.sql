-- Драйвер SIP у абонента: старый chan_sip или новый chan_pjsip.
--
-- Зачем отдельное поле. Изначально драйвер выбирался по типу абонента:
-- устройства — старый драйвер, приложения — новый. После обновления прошивок
-- вызывных панелей новый драйвер заработал с ними корректно и даёт
-- предварительное видео, поэтому устройства переводим на него — но не все
-- сразу, а по одному, и на время перехода номеру нужна конфигурация сразу
-- в двух драйверах: устройство подключается к новому порту, а остальные
-- продолжают работать как работали.
--
-- Значения:
--   ''      — по типу абонента, как было: устройства — старый, приложения — новый
--   'sip'   — только старый драйвер
--   'pjsip' — только новый драйвер
--   'both'  — секции в обоих драйверах, вызов идёт в оба (переходное состояние)
--
-- Пустое значение по умолчанию выбрано намеренно: существующие установки
-- после миграции ведут себя ровно как раньше, и переход не начинается сам
-- собой — его делает человек, по одному устройству.
ALTER TABLE sip_accounts ADD COLUMN IF NOT EXISTS driver text NOT NULL DEFAULT '';
