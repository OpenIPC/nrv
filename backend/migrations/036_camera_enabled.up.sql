-- Признак «камера выключена».
--
-- Выключенная камера остаётся в справочнике — с расписанием, зонами и
-- историей событий, — но система к ней не обращается: поток не поднимается
-- в медиасервере, кадры не публикуются, детекция и запись не идут, а
-- мониторинг не считает её пропавшей.
--
-- Нужно для двух случаев: камера временно недоступна (ремонт, переезд,
-- работы в помещении) и ограничение нагрузки при испытаниях, когда часть
-- камер намеренно держат выключенными. Удалять камеру в таких случаях
-- нельзя: вместе с ней ушли бы архивные записи и привязки.
ALTER TABLE cameras ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE;
