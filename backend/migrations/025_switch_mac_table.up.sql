-- Таблица MAC-адресов коммутатора и уточнение нумерации портов.
--
-- Зачем таблица MAC: она отвечает на вопрос, который иначе приходится
-- решать вручную — какая камера подключена к какому порту. Коммутатор
-- сообщает список адресов вместе с портом, и по нему привязку можно
-- предложить оператору или проставить сама.
--
-- Отдельная таблица, а не поле в switch_ports: адресов на коммутаторе
-- до нескольких десятков, и они не совпадают с портами один к одному —
-- через транзитный порт видно сразу много устройств. Хранить список в
-- поле порта пришлось бы строкой, и искать по ней нельзя.

CREATE TABLE IF NOT EXISTS switch_mac_entries (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    switch_id   UUID NOT NULL REFERENCES switches(id) ON DELETE CASCADE,
    -- Адрес приводится к виду без разделителей в нижнем регистре: в таком
    -- виде его отдаёт устройство, и в таком же виде сравниваем с базой
    -- камер. Форматы хранения у коммутатора и у камеры различаются, и
    -- сравнение «как есть» не находило бы совпадений вовсе.
    mac         VARCHAR(12) NOT NULL,
    -- Номер порта на корпусе. NULL означает, что модель не сообщила порт:
    -- часть прошивок отдаёт одинаковую маску для всех записей, и тогда
    -- привязать адрес к порту невозможно. Это не ошибка разбора, а
    -- свойство устройства, поэтому храним именно NULL, а не 0.
    port_number SMALLINT,
    -- Через транзитный порт видно чужие устройства. Признак нужен, чтобы
    -- не предлагать привязку камеры к транзитному порту: там её нет.
    via_uplink  BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (switch_id, mac)
);

CREATE INDEX IF NOT EXISTS idx_switch_mac_entries_switch ON switch_mac_entries (switch_id);
CREATE INDEX IF NOT EXISTS idx_switch_mac_entries_mac ON switch_mac_entries (mac);

