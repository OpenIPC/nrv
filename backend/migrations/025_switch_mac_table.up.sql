-- Состояние таблицы MAC у конкретного коммутатора.
--
-- Различаем три случая, потому что действия оператора в них разные:
--   ok          — порты сообщаются, привязки можно определять;
--   no_ports    — таблица есть, но порт в ней не указан (прошивка
--                 заполняет маску одинаково) — привязку задаём вручную;
--   unsupported — команда не поддерживается моделью;
--   unknown     — ещё не опрашивали.
ALTER TABLE switches ADD COLUMN IF NOT EXISTS mac_table_state VARCHAR(20) NOT NULL DEFAULT 'unknown';

-- Пояснение к состоянию словами: показывается оператору вместо того,
-- чтобы он гадал, почему кнопка неактивна.
ALTER TABLE switches ADD COLUMN IF NOT EXISTS mac_table_note TEXT NOT NULL DEFAULT '';

-- ---------------------------------------------------------------------------

-- Число портов с PoE.
--
-- Нужно для перевода номера порта во внутренний индекс и обратно.
-- Устройство переворачивает нумерацию только у портов PoE, а транзитные
-- оставляет в конце, поэтому одной длины списка портов недостаточно —
-- нужно знать, где кончаются PoE-порты.
--
-- Храним отдельно, потому что перевод требуется при отправке команды,
-- а читать ради этого состояние всех портов накладно.
ALTER TABLE switches ADD COLUMN IF NOT EXISTS poe_count SMALLINT NOT NULL DEFAULT 0;
