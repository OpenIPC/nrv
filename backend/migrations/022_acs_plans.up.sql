-- Точка на плане: устройство, привязанное к месту.
--
-- Одна таблица на все виды устройств, а не три отдельные: у камеры, двери
-- и считывателя на плане различаются только значок и подпись, а всё
-- остальное — координаты, поворот, подпись — одинаково. Три таблицы
-- пришлось бы одинаково править при каждом изменении отображения.
CREATE TABLE IF NOT EXISTS acs_plan_points (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    plan_id    UUID NOT NULL REFERENCES acs_plans(id) ON DELETE CASCADE,

    -- Вид устройства. Определяет, откуда берётся состояние и куда ведёт
    -- нажатие:
    --   camera     — камера видеонаблюдения;
    --   door       — дверь (проём) контроллера СКУД;
    --   controller — контроллер СКУД целиком;
    --   reader     — считыватель. Отдельно от двери, потому что
    --                считыватель и замок могут стоять в разных местах
    --                (считыватель снаружи, замок на двери).
    kind       VARCHAR(20) NOT NULL,

    -- Ссылка на устройство. Поле не имеет внешнего ключа: оно указывает
    -- в три разные таблицы в зависимости от kind, и внешний ключ здесь
    -- выразить нечем. Целостность обеспечивается при удалении устройства
    -- в сервисном слое — иначе точка осталась бы висеть на плане и
    -- показывать состояние несуществующего устройства.
    device_id  UUID,

    -- Координаты в долях от размера подложки: 0 — левый/верхний край,
    -- 1 — правый/нижний. См. пояснение в acs_plans.
    x          DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    y          DOUBLE PRECISION NOT NULL DEFAULT 0.5,

    -- Поворот значка в градусах: считыватель на плане принято рисовать
    -- «смотрящим» в сторону прохода.
    rotation   INTEGER NOT NULL DEFAULT 0,

    -- Подпись. Пусто — показываем имя устройства. Отдельная подпись
    -- нужна там, где имя в системе длинное («Z5R WEB BT (вход)»), а на
    -- плане уместно короткое («вход»).
    label      VARCHAR(100) NOT NULL DEFAULT '',

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT acs_plan_points_kind_check
        CHECK (kind IN ('camera', 'door', 'controller', 'reader')),
    -- Координаты за пределами подложки означают, что точка не видна на
    -- плане, и оператор будет искать её напрасно. Лучше отклонить запрос.
    CONSTRAINT acs_plan_points_coords_check
        CHECK (x >= 0 AND x <= 1 AND y >= 0 AND y <= 1)
);

CREATE INDEX IF NOT EXISTS idx_acs_plan_points_plan ON acs_plan_points (plan_id);
-- Индекс по устройству нужен для поиска «где на планах стоит эта камера»
-- и для уборки точек при удалении устройства.
CREATE INDEX IF NOT EXISTS idx_acs_plan_points_device ON acs_plan_points (device_id)
    WHERE device_id IS NOT NULL;

-- Одна точка на устройство в пределах плана.
--
-- Без этого ограничения двойной клик по кнопке «добавить» создал бы две
-- точки в одном месте, и оператор правил бы их по отдельности, не
-- понимая, почему значок «дёргается».
CREATE UNIQUE INDEX IF NOT EXISTS idx_acs_plan_points_unique
    ON acs_plan_points (plan_id, kind, device_id)
    WHERE device_id IS NOT NULL;
