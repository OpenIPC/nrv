-- Планы помещений: подложка и расстановка устройств.
--
-- Задача, под которую это сделано: при обходе и при разборе происшествия
-- нужно видеть, где стоит конкретная камера, дверь или считыватель, и
-- работают ли они прямо сейчас. Списком это неудобно: в списке нет
-- соседства, а именно оно важно — «камера у входа» и «дверь у входа»
-- связаны между собой, и в списке этой связи не видно.
--
-- Отдельная таблица на план, а не поля в устройстве: план один, а
-- устройств на нём много, и одному устройству может соответствовать
-- несколько точек — на разных этажах и схемах. Обратное отношение
-- (поле plan_id в камере) заставляло бы дублировать устройство.
--
-- Координаты хранятся в долях от размера подложки (0..1), а не в
-- пикселях. Это важно: план могут заменить на снимок большего размера,
-- и точки при этом должны остаться на своих местах, а не уехать в угол.
-- Пересчёт в пиксели делает интерфейс, зная размер картинки.

CREATE TABLE IF NOT EXISTS acs_plans (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name        VARCHAR(200) NOT NULL,
    -- Описание: «Первый этаж, левое крыло».
    description VARCHAR(500) NOT NULL DEFAULT '',
    -- Подложка: изображение плана. Формат хранения тот же, что у
    -- фотографий владельцев и эталонных снимков: "minio:<key>" или
    -- "local:<путь>". Храним путь, а не двоичные данные: снимок этажа
    -- весит сотни килобайт, и в базе ему не место.
    image_path  VARCHAR(512) NOT NULL DEFAULT '',
    -- Порядок в списке: оператор расставляет планы от общего к частному
    -- (сначала этажи, потом отдельные помещения).
    sort_order  INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_acs_plans_sort ON acs_plans (sort_order, name);

