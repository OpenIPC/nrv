-- Старый драйвер SIP больше не используется: устройства перевели на chan_pjsip.
--
-- Поле driver появлялось для постепенного перевода: «both» означало секции в
-- двух драйверах, чтобы переводить устройства по одному. Владелец решил не
-- возиться с переходным состоянием и уйти от старого драйвера целиком: он
-- удалён из новых ветвей Asterisk, а новый драйвер после обновления прошивок
-- панелей работает со всеми нашими устройствами (в том числе даёт
-- предварительное видео с панели).
--
-- Поэтому поле удаляем: драйвер один, и хранить его у абонента незачем.
ALTER TABLE sip_accounts DROP COLUMN IF EXISTS driver;
