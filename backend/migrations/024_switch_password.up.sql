-- Пароль коммутатора и признак транзитного порта.
--
-- Зачем пароль: устройства этой линейки ведут себя по-разному. PS204
-- отдаёт состояние без авторизации, а GPS204V3 на запрос без входа
-- отвечает текстом «Please conduct security verification first». Без
-- сохранённого пароля такие коммутаторы оказались бы «недоступными» в
-- интерфейсе при полностью исправной связи.
--
-- Пароль не хешируется, и это осознанно: он не проверяется нами, а
-- пересылается устройству как есть — протокол не предусматривает
-- иначе. Хеширование сделало бы отправку невозможной, а не безопасной.
ALTER TABLE switches ADD COLUMN IF NOT EXISTS password VARCHAR(200) NOT NULL DEFAULT '';

-- Признак транзитного порта (uplink).
--
-- Такие порты нельзя выключать: через них идёт весь трафик коммутатора,
-- включая связь с нашим сервером. Без отдельного признака оператор мог бы
-- нажать «выключить питание» на восходящем порту и отрезать весь
-- коммутатор от сети, включая самого себя.
--
-- Признак приходит от устройства битовой маской (поле uplink) и хранится
-- отдельной колонкой, потому что решение о запрете команды принимается
-- до обращения к устройству.
ALTER TABLE switch_ports ADD COLUMN IF NOT EXISTS is_uplink BOOLEAN NOT NULL DEFAULT FALSE;
