-- Настройки медиа домофонии: адрес STUN и диапазон портов для разговора.
--
-- Зачем это в базе, а не в файлах Asterisk. Установка разворачивается в
-- разных домах: внешний адрес, свои сети и порты у всех разные, а править
-- rtp.conf руками на каждом сервере — значит требовать от оператора доступа
-- к файлам. Теперь значения задаются на странице «Домофония», а сервер
-- собирает из них конфигурацию Asterisk.
--
-- stun_server — через STUN станция узнаёт свой внешний адрес и предлагает
-- его приложениям внешним ICE-кандидатом. Без этого телефон в мобильной
-- сети не понимает, куда отправлять звук и видео: звонок проходит, а
-- разговора нет. Значение по умолчанию — проверенный рабочий сервер; с
-- stun.l.google.com запросы станции оставались без ответа.
--
-- Диапазон портов нужен, чтобы знать, что пробрасывать на роутере: один
-- разговор занимает по порту в каждую сторону. Значение по умолчанию
-- совпадает с тем, что стояло в rtp.conf.
ALTER TABLE sip_settings
    ADD COLUMN IF NOT EXISTS stun_server    TEXT NOT NULL DEFAULT 'stun.sipnet.ru:3478',
    ADD COLUMN IF NOT EXISTS rtp_port_start INTEGER NOT NULL DEFAULT 10000,
    ADD COLUMN IF NOT EXISTS rtp_port_end   INTEGER NOT NULL DEFAULT 10100;
