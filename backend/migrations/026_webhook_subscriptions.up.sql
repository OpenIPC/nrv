-- Подписки на вебхуки о событиях.
--
-- Зачем отдельная таблица, а не поле в настройках сервера: подписок может
-- быть несколько и они разнородные — интеграция умного дома, мобильное
-- приложение, сторонний приёмник. В настройках пришлось бы держать список
-- в JSON, и тогда нельзя было бы ни отключить одну подписку, не трогая
-- остальные, ни хранить по каждой время последней удачной доставки.
--
-- Доставка идёт по HTTP POST на адрес приёмника. Адрес — единственный
-- ключ подписки: повторная регистрация того же адреса должна обновлять
-- подписку, а не заводить вторую. Иначе при каждом перезапуске интеграции
-- в базе копился бы дубль, и сервер слал бы события дважды.
CREATE TABLE IF NOT EXISTS webhook_subscriptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Адрес приёмника.
    url TEXT NOT NULL,

    -- Общий секрет для подписи тела запроса (HMAC-SHA256).
    --
    -- Подпись нужна потому, что приёмник находится в домашней сети и
    -- доступен всем в ней. Без неё любое устройство могло бы отправить
    -- поддельное событие «человек в кадре» и запустить автоматизацию.
    secret VARCHAR(200) NOT NULL DEFAULT '',

    -- Человекочитаемое имя: по нему подписка опознаётся в списке.
    name VARCHAR(200) NOT NULL DEFAULT '',

    -- Выключенная подписка остаётся в базе, но события не получает.
    -- Нужно, чтобы отладить приёмник, не удаляя подписку.
    enabled BOOLEAN NOT NULL DEFAULT TRUE,

    -- Фильтры. Пустой список означает «без ограничений», а не «ничего
    -- не присылать»: так подписка, заведённая «на всё», продолжает
    -- работать и после появления новых классов объектов в детекторе.
    event_types TEXT[] NOT NULL DEFAULT '{}',
    camera_ids UUID[] NOT NULL DEFAULT '{}',

    -- Состояние последней доставки. Оператору нужно видеть, жива ли
    -- подписка, а не догадываться об этом по отсутствию событий.
    last_status INT NOT NULL DEFAULT 0,
    last_error TEXT NOT NULL DEFAULT '',
    last_delivery_at TIMESTAMPTZ,
    -- Счётчик подряд неудачных доставок: по нему видно, что приёмник
    -- отвалился надолго, а не моргнул один раз.
    failure_count INT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS webhook_subscriptions_url_uniq
    ON webhook_subscriptions (url);

-- Индекс по включённым подпискам: рассылка при каждом событии выбирает
-- именно их, и выключенные мешать не должны.
CREATE INDEX IF NOT EXISTS webhook_subscriptions_enabled_idx
    ON webhook_subscriptions (enabled) WHERE enabled;
