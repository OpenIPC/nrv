-- Зоны игнорирования: несколько полигонов, внутри которых объекты не считаются.
--
-- Зачем отдельно от zone. zone — это «белый список»: искать только здесь.
-- Нужен и обратный случай: камера смотрит на дорогу за забором, на ветки
-- перед объективом или на соседний участок, и всё это даёт поток событий,
-- которые никому не нужны. Перекрывать их белой зоной неудобно: зона
-- получается сложной и её приходится перерисовывать при каждом изменении
-- сцены. Чёрные зоны проще — их можно накладывать по одной.
--
-- Формат: массив полигонов, каждый — массив точек {"x":0..1,"y":0..1}.
-- Пустой массив означает «игнорировать нечего».
ALTER TABLE detection_settings
    ADD COLUMN IF NOT EXISTS ignore_zones jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN detection_settings.ignore_zones IS
    'Зоны игнорирования: массив полигонов, внутри которых объекты не считаются';
