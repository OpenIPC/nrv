-- Временная блокировка учётной записи.
--
-- Две колонки, а не одна: «заблокирован» и «до какого времени» отвечают на
-- разные вопросы. Отдельный флажок позволяет заблокировать бессрочно
-- (blocked_until пусто), не выдумывая для этого дату-заглушку вроде 2100 года,
-- которая потом попадала бы в интерфейс как настоящее время разблокировки.
--
-- Блокировка проверяется при входе и на каждом запросе: иначе заблокированный
-- продолжал бы работать по уже выданному токену (он живёт сутки) и снять
-- блокировку в интерфейсе не имело бы смысла.
--
-- Просроченная блокировка снимается сама при чтении учётной записи: если бы
-- её снимал только администратор руками, «заблокирован на час» оставался бы
-- блокировкой навсегда.

ALTER TABLE users ADD COLUMN IF NOT EXISTS blocked boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS blocked_until timestamptz;
-- Причина необязательна, но её полезно видеть в карточке: «заблокирован»
-- без причины заставляет администратора спрашивать коллег, что случилось.
ALTER TABLE users ADD COLUMN IF NOT EXISTS block_reason varchar(200) NOT NULL DEFAULT '';

-- Индекс для автоснятия просроченных блокировок: их ищут при каждом чтении
-- учётной записи, и без индекса это был бы просмотр всей таблицы.
CREATE INDEX IF NOT EXISTS idx_users_blocked_until
    ON users(blocked_until)
    WHERE blocked = true;
