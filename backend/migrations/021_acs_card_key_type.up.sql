-- Тип ключа: простой, мастер, блокирующий.
--
-- До этой миграции мы различали только «активна карта или нет», и этого
-- хватало, пока доступ либо был, либо нет. У контроллеров IronLogic
-- ключ имеет тип, и типы — не украшение журнала, а разные режимы работы:
--
--   simple   — обычный пропуск;
--   master   — служебный ключ для программирования контроллера: им
--              меняют режимы и записывают другие ключи, проход он
--              не открывает;
--   blocking — ключ-переключатель: меняет режим контроллера (например
--              ставит блокировку). В обычном состоянии работает и как
--              пропуск.
--
-- Почему это не выводится из существующих полей: заблокированная карта
-- (active = false) и мастер-ключ — разные вещи. Первая не должна пускать
-- никого и никогда, второй обязан работать, но по служебному назначению.
-- Пока типа не было, мастер-ключ приходилось заводить обычным — и он
-- либо не работал как мастер, либо открывал дверь, чего быть не должно.

ALTER TABLE acs_cards
    ADD COLUMN IF NOT EXISTS key_type VARCHAR(16) NOT NULL DEFAULT 'simple';

-- Ограничение перечислением, а не справочной таблицей: значений всего
-- три, они заданы протоколом контроллера и меняться не будут. Отдельная
-- таблица усложнила бы запросы и потребовала бы миграции данных при
-- каждом разворачивании.
ALTER TABLE acs_cards
    DROP CONSTRAINT IF EXISTS acs_cards_key_type_check;

ALTER TABLE acs_cards
    ADD CONSTRAINT acs_cards_key_type_check
    CHECK (key_type IN ('simple', 'master', 'blocking'));

-- Индекс нужен для выборок «покажи мастер-ключи объекта»: их единицы
-- на сотни обычных, и без индекса такой запрос читал бы всю таблицу.
CREATE INDEX IF NOT EXISTS idx_acs_cards_key_type
    ON acs_cards (key_type)
    WHERE key_type <> 'simple';
