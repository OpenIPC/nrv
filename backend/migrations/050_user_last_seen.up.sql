-- Время последнего обращения учётной записи к серверу.
--
-- Зачем: на странице пользователей администратору нужно видеть, работает
-- человек сейчас или нет. Без отметки это неоткуда взять — вход в систему
-- происходит раз в сутки, а токен живёт всё это время, и «вошёл» ничего не
-- говорит о том, кто сейчас за экраном.
--
-- Отметка не является журналом входов: она обновляется раз в минуту на
-- каждый активный запрос, и старые значения перезаписываются. Для разбора
-- «кто и когда входил» служит отдельный механизм, а здесь нужен только
-- текущий признак присутствия.
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;
