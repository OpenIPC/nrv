-- Состояние присмотра за Majestic по каждой камере.
--
-- Зачем отдельная таблица, а не поля камеры: состояние меняется постоянно
-- (счётчик перезапусков, время последней проверки), а карточка камеры —
-- редко. Если смешать их, оператор увидит в форме постоянно прыгающие
-- цифры, а каждое обновление счётчика будет переписывать запись камеры.
--
-- Строка создаётся по мере появления камеры в присмотре: заводить её
-- заранее для всех камер значило бы держать пустые записи для тех, что
-- ещё ни разу не проверялись.

CREATE TABLE IF NOT EXISTS majestic_watch (
    camera_id UUID PRIMARY KEY REFERENCES cameras(id) ON DELETE CASCADE,

    -- Сколько раз Majestic перезапускали в текущем окне.
    restart_count INTEGER NOT NULL DEFAULT 0,
    -- Начало текущего окна подсчёта.
    --
    -- Окно скользящее, а не «сутки календарные»: важно, сколько падений
    -- было за последние сутки от текущего момента, а не с полуночи.
    -- При календарном окне всплеск падений вечером обнулялся бы в полночь,
    -- и камера, падающая каждый вечер, выглядела бы исправной.
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    last_restart_at TIMESTAMPTZ,
    last_reboot_at  TIMESTAMPTZ,

    -- Состояние при последней проверке: ok, fallen, unknown.
    last_state TEXT NOT NULL DEFAULT '',
    last_check_at TIMESTAMPTZ,
    last_error    TEXT NOT NULL DEFAULT '',

    -- До какого момента камеру не проверять: после перезапуска Majestic
    -- поднимается не мгновенно, и проверка сразу после команды решила бы,
    -- что перезапуск не помог, и полезла бы снова.
    cooldown_until TIMESTAMPTZ,

    -- Последняя значимая строка из логов камеры. Показывается оператору
    -- вместе с сообщением о падении: чаще всего причина видна именно там,
    -- и искать её отдельно не приходится.
    last_log_hint TEXT NOT NULL DEFAULT ''
);

-- Поиск камер, которые сейчас на паузе, и выборка проблемных для страницы.
CREATE INDEX IF NOT EXISTS idx_majestic_watch_state
    ON majestic_watch (last_state, last_check_at DESC);
