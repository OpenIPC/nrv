-- 019: расширение справочника карт СКУД.
--
-- Причина изменений — контроллер Z5R WEB BT. Он работает не с Wiegand-26,
-- а с шестибайтовым кодом: два старших байта — facility, четыре младших —
-- номер карты. Значит, facility занимает 16 бит, а номер — 32 бита, и
-- прежние ограничения (facility 8 бит, card 16 бит) отсекали почти все
-- реальные карты. Проверено на живом контроллере: все 21 карта парка
-- имели номер больше 65535, то есть в старую схему не помещались ни одна.
--
-- Помимо диапазона добавляются сведения о владельце карты. Раньше хватало
-- имени, но для проходной нужны должность, уровень доступа и фотография:
-- оператор должен видеть, кому принадлежит карта, и уметь показать фото
-- охране. Фотография хранится так же, как эталонные снимки лиц
-- (см. 005_faces_plates.up.sql): строка вида "minio:<key>" или "local:<path>",
-- а не двоичные данные — иначе база распухнет от снимков.

-- ---------------------------------------------------------------------------
-- Расширение диапазонов.
--
-- Ограничения снимаются и ставятся заново: PostgreSQL не умеет менять
-- условие CHECK на месте. Значения взяты из формата контроллера: facility
-- 16 бит, номер карты 32 бита.
-- ---------------------------------------------------------------------------
ALTER TABLE acs_cards DROP CONSTRAINT IF EXISTS acs_cards_facility_range;
ALTER TABLE acs_cards DROP CONSTRAINT IF EXISTS acs_cards_card_range;

ALTER TABLE acs_cards
    ADD CONSTRAINT acs_cards_facility_range CHECK (facility BETWEEN 0 AND 65535),
    -- Верхняя граница — предел 32-битного беззнакового числа, то есть
    -- максимальный номер карты в формате контроллера.
    ADD CONSTRAINT acs_cards_card_range CHECK (card BETWEEN 0 AND 4294967295);

-- ---------------------------------------------------------------------------
-- Сведения о владельце карты.
-- ---------------------------------------------------------------------------

-- Должность владельца карты: «Электрик», «Бухгалтер».
-- Пустая строка вместо NULL: в интерфейсе это одно и то же («не указано»),
-- а с NULL пришлось бы отдельно обрабатывать отсутствие значения в каждом
-- запросе и в каждой форме.
ALTER TABLE acs_cards ADD COLUMN IF NOT EXISTS position VARCHAR(128) NOT NULL DEFAULT '';

-- Уровень доступа — номер права прохода по нашей классификации.
--
-- Отдельное поле, а не группа (grp): группа описывает принадлежность
-- (например, «подрядчики»), а уровень задаёт, куда человеку можно.
-- 0 — базовый уровень, значения выше — расширенные. Конкретный смысл
-- уровней задаёт оператор, поэтому в схеме нет списка значений: он
-- зависит от объекта, и вписывать его в базу значило бы привязать
-- систему к одной установке.
ALTER TABLE acs_cards ADD COLUMN IF NOT EXISTS access_level INTEGER NOT NULL DEFAULT 0;

-- Фотография владельца карты: "minio:<key>" или "local:<абсолютный путь>".
-- Формат совпадает с known_faces.photo_path, поэтому показ и чтение
-- переиспользуют уже готовые функции хранилища.
ALTER TABLE acs_cards ADD COLUMN IF NOT EXISTS photo_path VARCHAR(512) NOT NULL DEFAULT '';

-- ---------------------------------------------------------------------------
-- Служебные поля для обновления базы на контроллере.
-- ---------------------------------------------------------------------------

-- Нужно ли выгружать карту на устройство.
--
-- Флаг появился из-за того, что база карт живёт в двух местах: на сервере
-- (с фото, должностью и уровнем — это наши поля, контроллер их не знает)
-- и на самом контроллере (только код карты и зоны доступа). Полная
-- выгрузка при каждом изменении переписывала бы всю базу на устройстве,
-- а это лишние обращения по Wi-Fi и риск потерять связь в середине записи.
-- Поэтому помечаем только изменённые карты, а остальные не трогаем.
ALTER TABLE acs_cards ADD COLUMN IF NOT EXISTS sync_pending BOOLEAN NOT NULL DEFAULT true;

-- Время последней выгрузки карты на контроллер. Пусто — карта на
-- устройстве ещё не подтверждена.
ALTER TABLE acs_cards ADD COLUMN IF NOT EXISTS synced_at TIMESTAMPTZ;

-- ---------------------------------------------------------------------------
-- Индексы.
-- ---------------------------------------------------------------------------

-- Поиск карт, ожидающих выгрузки на контроллер: по этому условию
-- строится список для синхронизации.
CREATE INDEX IF NOT EXISTS idx_acs_cards_pending
    ON acs_cards (controller_id) WHERE sync_pending = true;

-- Поиск владельца по должности и уровню доступа — для фильтров в интерфейсе.
CREATE INDEX IF NOT EXISTS idx_acs_cards_access_level
    ON acs_cards (access_level);

COMMENT ON COLUMN acs_cards.position IS 'Должность владельца карты; "" — не указана';
COMMENT ON COLUMN acs_cards.access_level IS 'Уровень доступа: номер права прохода, смысл задаёт оператор';
COMMENT ON COLUMN acs_cards.photo_path IS 'Фото владельца: minio:<key> или local:<абсолютный путь>';
COMMENT ON COLUMN acs_cards.sync_pending IS 'Карта изменена и ждёт выгрузки на контроллер';
COMMENT ON COLUMN acs_cards.synced_at IS 'Когда карта последний раз выгружена на контроллер';
