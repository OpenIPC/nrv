-- Исправление производителей: определяем по MAC-адресу.
--
-- Предыдущая миграция (017) определяла OpenIPC по косвенным признакам —
-- пустой прошивке, «sub:» в строке, модели сенсора. Это оказалось
-- ошибкой: пустое поле означает «не удалось прочитать версию», а не
-- «установлена OpenIPC». В результате пять камер получили вендора,
-- которого у них нет:
--
--   192.168.1.8, .44, .45  — Vivotek (MAC 00:02:d1)
--   192.168.1.11           — Beward  (MAC 18:68:82, домофон DS07P-LP)
--   192.168.1.164          — Hikvision (MAC c0:51:7e)
--
-- Признаки, подтверждённые прямыми проверками этих камер: SSH закрыт
-- (на OpenIPC он всегда открыт), HTTP-заголовки чужие («streaming_server»
-- у Vivotek, «IPCamera-Webs» и digest-realm с названием модели у Beward),
-- RTSP-пути не похожи на openipc-шные («live1s1», «media/stream.sdp»,
-- «av0_0» вместо «stream=0»).
--
-- MAC надёжнее версии прошивки: адрес выдаёт производитель железа, и он
-- остаётся прежним после перепрошивки. Поэтому определение начинается
-- с него.

-- Vivotek. 00:02:d1 — префикс производителя, три камеры в парке.
UPDATE cameras SET vendor = 'vivotek'
WHERE mac ILIKE '00:02:d1%'
   OR ip IN ('192.168.1.8', '192.168.1.44', '192.168.1.45');

-- Beward. 18:68:82 — префикс, совпадает с тем, что камера сама сообщила
-- в digest-realm: «DS07P-LP SIP Door Station».
UPDATE cameras SET vendor = 'beward'
WHERE mac ILIKE '18:68:82%'
   OR ip = '192.168.1.11';

-- Hikvision: добавляем .164, у которого прошивку прочитать не удалось.
UPDATE cameras SET vendor = 'hikvision'
WHERE ip = '192.168.1.164';

-- Остальные камеры OpenIPC.
--
-- Здесь признак обратный: OpenIPC подтверждается не пустой прошивкой,
-- а тем, что все остальные признаки ЭТОЙ установки сходятся —
-- RTSP-путь «stream=0» (фирменный для Majestic), наличие SSH, отсутствие
-- чужого вендора по MAC.
--
-- Ограничиваем список явными адресами, а не условием по прошивке: так
-- исправление не заденет камеру, добавленную позже. Новые камеры
-- определяются сканером по API Majestic, и это надёжнее любой миграции.
UPDATE cameras SET vendor = 'openipc'
WHERE ip IN (
  '192.168.1.5', '192.168.1.12', '192.168.1.28', '192.168.1.41',
  '192.168.1.48', '192.168.1.59', '192.168.1.61', '192.168.1.67',
  '192.168.1.75', '192.168.1.81', '192.168.1.83', '192.168.1.87',
  '192.168.1.103', '192.168.1.106', '192.168.1.135', '192.168.1.166'
);

-- Проверка, что список верен, делалась прямыми обращениями к камерам:
-- у всех перечисленных открыт SSH на 22 порту и отвечает API Majestic
-- (/api/v1/config.schema.json). У Vivotek, Beward и Hikvision из этого
-- списка нет ни одной — там SSH закрыт, а путь потока не «stream=0».
--
-- 192.168.1.5 стоит в списке намеренно, хотя её прошивка выглядит чужой
-- («os02g10_i2c_1080p»). Проверено: SSH открыт, Majestic API отвечает 401,
-- то есть это OpenIPC с нестандартным значением в поле прошивки.
