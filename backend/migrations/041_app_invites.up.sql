-- Коды приглашения для подключения мобильного приложения.
--
-- Зачем отдельная таблица, а не показ пароля в QR. Пароль в квадратике на
-- экране живёт столько же, сколько пароль: его сфотографируют, он попадёт
-- в галерею, останется на чужом мониторе. Код приглашения одноразовый и
-- с коротким сроком: перехваченный код либо уже использован, либо истёк.
--
-- Код привязан к человеку, а не к устройству: приложение получает ту же
-- учётную запись, что и вход по паролю, со всеми её правами.
CREATE TABLE IF NOT EXISTS app_invites (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- Код в открытом виде: он короткий, одноразовый и живёт минуты, а
    -- хранить его хешем мешало бы администратору проверить, что показано
    -- на экране именно то, что записано в базе.
    code varchar(64) NOT NULL UNIQUE,
    -- Кто выдал приглашение: при разборе происшествия важно знать, чей это
    -- был экран. SET NULL — приглашение само по себе ценно и после
    -- удаления выдавшего.
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    expires_at timestamptz NOT NULL,
    -- Пусто, пока код не использован: по этому признаку код одноразовый.
    used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Приглашения ищут по человеку: при новой выдаче прежние неиспользованные
-- аннулируются, и найти их надо быстро.
CREATE INDEX IF NOT EXISTS idx_app_invites_user ON app_invites(user_id);
