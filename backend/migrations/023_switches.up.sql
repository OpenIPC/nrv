-- Управляемые PoE-коммутаторы: учёт устройств и мониторинг портов.
--
-- Задача, под которую это сделано: камеры питаются от PoE-коммутаторов, и
-- при «пропаже» камеры оператор не может отличить три разные причины:
--   * камера зависла — лечится снятием и подачей питания на порт;
--   * обрыв линии или сгорел порт — питание не поможет, нужен ремонт;
--   * камера исправна, но не отвечает по сети — питание есть и есть линк.
-- Без данных с коммутатора все три случая выглядят одинаково — «офлайн»,
-- и оператор наугад перезагружает камеру. С данными о порте видно
-- потребление и линк, и причина определяется сразу.
--
-- Отдельные таблицы для коммутаторов, а не «камера ссылается на порт»:
-- на порту может не быть камеры вовсе (транзит, восходящий канал), а один
-- коммутатор обслуживает много камер. Кроме того, коммутатор живёт сам по
-- себе — он есть в сети даже когда камеры на нём отключены.

CREATE TABLE IF NOT EXISTS switches (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Серийный номер — главный идентификатор: по нему устройство отзывается
    -- на широковещательный поиск в мультикасте, и он не меняется при смене
    -- адреса. Адрес меняется (DHCP), серийный номер — нет.
    sn          VARCHAR(64)  NOT NULL UNIQUE,
    mac         VARCHAR(32)  NOT NULL DEFAULT '',
    ip          VARCHAR(64)  NOT NULL DEFAULT '',
    model       VARCHAR(64)  NOT NULL DEFAULT '',
    firmware    VARCHAR(64)  NOT NULL DEFAULT '',
    -- Название для оператора. Размножение по объектам подразумевает, что
    -- «Коммутатор 2 этаж» осмысленно, а серийный номер — нет.
    name        VARCHAR(200) NOT NULL DEFAULT '',
    -- Расположение: «Серверная», «Щит у входа». Нужно, когда коммутаторов
    -- больше одного и надо понимать, куда идти при неисправности.
    location    VARCHAR(300) NOT NULL DEFAULT '',
    -- Полный ответ устройства (напряжение, температура, трафик по портам и
    -- т.д.). Храним целиком, а не по полям: набор полей зависит от модели
    -- и прошивки, и жёсткая схема ломалась бы на новом устройстве. Разбор
    -- делает код, который умеет переживать отсутствие поля.
    detail      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    -- Напряжение питания и температура — отдельными полями, хотя приходят
    -- в составе общего ответа. Нужны в списке и на плане постоянно, а
    -- разбирать ради двух чисел весь JSON на каждом кадре интерфейса
    -- расточительно.
    voltage     REAL         NOT NULL DEFAULT 0,
    temperature REAL         NOT NULL DEFAULT 0,
    -- Число портов PoE. Определяет, сколько строк рисовать в интерфейсе.
    -- Храним отдельно, потому что по нему строится таблица портов, и
    -- читать ради этого весь detail накладно.
    port_count  SMALLINT     NOT NULL DEFAULT 0,
    -- Порядок нумерации портов у разных моделей разный: у части моделей
    -- физический порт 1 соответствует последнему индексу в ответе. Если
    -- это не учесть, перезагрузка попадёт не в ту камеру — то есть
    -- оператор отключит исправное устройство вместо зависшего.
    ports_reversed BOOLEAN    NOT NULL DEFAULT FALSE,
    -- Коммутатор сам сообщил о себе при последней синхронизации. Отличается
    -- от «недоступен»: устройство может быть выключено, а может быть
    -- перенесено в другую подсеть. Разные причины — разные действия.
    online      BOOLEAN      NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMPTZ,
    -- Последняя ошибка связи — текст для оператора, чтобы не гадать,
    -- почему коммутатор «офлайн»: таймаут это или отказ авторизации.
    last_error  TEXT         NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_switches_name ON switches (name, model);

-- ---------------------------------------------------------------------------

-- Порты коммутатора: состояние на момент последнего опроса.
--
-- Это не журнал, а снимок текущего состояния: строку перезаписываем при
-- каждом опросе. Журнал изменений — отдельная задача и отдельная таблица;
-- держать историю здесь значило бы растить базу на ровном месте при
-- опросе раз в минуту.
CREATE TABLE IF NOT EXISTS switch_ports (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    switch_id   UUID NOT NULL REFERENCES switches(id) ON DELETE CASCADE,
    -- Номер порта, как он подписан на корпусе, — то есть как его видит
    -- оператор. Именно это число показываем и по нему даём команды.
    port_number SMALLINT NOT NULL,

    -- Есть ли линк. Ключевой признак: питание может подаваться, а связи
    -- не быть — тогда проблема в кабеле или в самом устройстве.
    link_up     BOOLEAN  NOT NULL DEFAULT FALSE,
    -- Скорость в Мбит/с (0, если линка нет).
    speed_mbps  INTEGER  NOT NULL DEFAULT 0,

    -- Питание PoE: включено ли оно на порту, и сколько ватт реально
    -- потребляет подключённое устройство. Потребление — самая полезная
    -- величина: ноль при включённом питании означает, что нагрузки нет,
    -- а растущее потребление часто предшествует отказу.
    poe_enabled BOOLEAN  NOT NULL DEFAULT FALSE,
    poe_watts   REAL     NOT NULL DEFAULT 0,
    -- Порт умеет питать (PoE-порт) или это транзитный/uplink порт. На
    -- транзитных портах питание не отдаётся, и выключать там нечего —
    -- запрет на команду должен быть виден в интерфейсе заранее.
    poe_capable BOOLEAN  NOT NULL DEFAULT FALSE,
    -- Расширенный режим: снижение скорости ради удлинения линии. Нужен
    -- на длинных пролётах и на плохих кабелях.
    extend_mode BOOLEAN  NOT NULL DEFAULT FALSE,
    -- Изоляция портов: порты не видят друг друга, каждый идёт только на
    -- uplink. Полезно, чтобы скомпрометированная камера не дотянулась до
    -- соседей по коммутатору.
    isolated    BOOLEAN  NOT NULL DEFAULT FALSE,

    -- Трафик за время работы коммутатора, в мегабайтах. Не «скорость»:
    -- по одним лишь счётчикам нельзя судить о текущей нагрузке, зато
    -- видно, работала ли камера вообще и сколько передала.
    tx_mb       REAL     NOT NULL DEFAULT 0,
    rx_mb       REAL     NOT NULL DEFAULT 0,

    -- Команда перезагрузки питания (снять и снова подать). Храним время,
    -- потому что оператор должен видеть, что она уже была недавно: иначе
    -- повторные перезагрузки одной и той же камеры останутся незамеченными.
    last_power_cycle_at TIMESTAMPTZ,

    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (switch_id, port_number)
);

CREATE INDEX IF NOT EXISTS idx_switch_ports_switch ON switch_ports (switch_id, port_number);

-- ---------------------------------------------------------------------------

-- Привязка камеры к порту коммутатора.
--
-- Отдельная таблица, а не поля в camera: камера может переехать на другой
-- порт или на другой коммутатор, и эту связь должен уметь поправить
-- оператор через интерфейс, не трогая карточку камеры. Плюс нужна
-- история — кто и когда назначил, чтобы при неверной привязке (и
-- ошибочной перезагрузке) было понятно, откуда она взялась.
--
-- Порт задаётся парой (коммутатор, номер) и он должен существовать. Это
-- защита от привязки камеры к порту, которого нет: по такой привязке
-- перезагрузка ушла бы «в пустоту», а оператор считал бы, что камеру
-- перезагрузили.
CREATE TABLE IF NOT EXISTS camera_switch_port (
    camera_id   UUID PRIMARY KEY REFERENCES cameras(id) ON DELETE CASCADE,
    switch_id   UUID NOT NULL REFERENCES switches(id) ON DELETE CASCADE,
    port_number SMALLINT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_camera_switch_port_switch ON camera_switch_port (switch_id, port_number);

-- ---------------------------------------------------------------------------

-- Журнал действий с питанием портов.
--
-- Зачем журнал, если есть поле last_power_cycle_at: поле отвечает на
-- вопрос «была ли перезагрузка», а журнал — «кто, когда, на сколько
-- секунд и чем закончилось». При разборе инцидента («камера пропала на
-- 40 минут») важно отличить отказ от последствий чужой перезагрузки.
CREATE TABLE IF NOT EXISTS switch_port_events (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    switch_id   UUID NOT NULL REFERENCES switches(id) ON DELETE CASCADE,
    switch_sn   VARCHAR(64) NOT NULL DEFAULT '',
    port_number SMALLINT NOT NULL,
    -- power_off, power_on, power_cycle, extend_on, extend_off
    action      VARCHAR(20) NOT NULL,
    -- ok или error.
    result      VARCHAR(10) NOT NULL DEFAULT 'ok',
    -- Текст ошибки устройства или связи.
    message     TEXT NOT NULL DEFAULT '',
    -- Инициатор: имя пользователя панели или 'system' для автоматики.
    actor       VARCHAR(100) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_switch_port_events_created ON switch_port_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_switch_port_events_port ON switch_port_events (switch_id, port_number, created_at DESC);
