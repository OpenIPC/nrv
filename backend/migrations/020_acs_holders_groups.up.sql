-- 020: пользователи, группы доступа и двери — основа подсистемы СКУД.
--
-- До этой миграции СКУД работал с картами напрямую: карта сама по себе
-- была и учётной записью, и владельцем, и носителем прав (всего лишь
-- колонка name с именем). Для одного контроллера и десятка карт этого
-- хватало, но система задумана как масштабируемая: контроллеры будут
-- добавляться и убираться, а людей станут объединять в отделы с общими
-- правами на общие двери.
--
-- Разделение сущностей вводится по трём причинам:
--
--  1. У одного человека бывает несколько карт — основная и брелок.
--     Пока карта была владельцем, уход сотрудника требовал вручную найти
--     и удалить все его носители, и одну забытую карту никто бы не
--     заметил. Теперь владелец один, а карт у него сколько угодно, и
--     отключение владельца отключает весь доступ сразу.
--
--  2. Права зависят от отдела, а не от человека. Бухгалтерии нужна одна
--     дверь, складу — другая. Заводить права каждому сотруднику вручную
--     значит повторять одни и те же действия и ошибаться при приёме
--     нового человека. Группа задаёт права один раз, человек в неё
--     включается.
--
--  3. Дверь — это не контроллер. У контроллера может быть два проёма
--     (вход и выход), и они могут требовать разных прав. Привязка прав
--     к контроллеру смешала бы эти случаи.

-- ---------------------------------------------------------------------------
-- Пользователи СКУД — владельцы карт.
-- ---------------------------------------------------------------------------
--
-- Отдельная таблица, а не поля в acs_cards: сведения о человеке
-- (должность, фото, отдел) живут независимо от того, каким носителем
-- он пользуется сегодня. Завтра он сменит карту, а запись о нём останется.
--
-- Таблица не связана с users (учётными записями интерфейса): это разные
-- сущности. Пользователь СКУД — сотрудник, который ходит через двери,
-- и учётная запись в веб-интерфейсе ему не нужна. Совпадение имён
-- возможно, но это разные люди или разные роли одного человека.
CREATE TABLE IF NOT EXISTS acs_holders (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    -- ФИО одной строкой: на проходной важно, как человека называть,
    -- а не из каких частей состоит его имя. Разделение потребовало бы
    -- правил для отчеств и составных фамилий без пользы для дела.
    full_name   VARCHAR(200) NOT NULL,
    -- Должность: «Электрик», «Бухгалтер».
    position    VARCHAR(128) NOT NULL DEFAULT '',
    -- Отдел как свободный текст: в разных организациях структура разная,
    -- и жёсткий справочник отделов только мешал бы. Права задаются
    -- группами доступа (ниже), а не отделом.
    department  VARCHAR(128) NOT NULL DEFAULT '',
    -- Фотография: "minio:<key>" или "local:<путь>", как у эталонных лиц.
    photo_path  VARCHAR(512) NOT NULL DEFAULT '',
    phone       VARCHAR(40) NOT NULL DEFAULT '',
    note        TEXT NOT NULL DEFAULT '',
    -- Уволенный сотрудник: доступ закрыт, но запись и история сохранены.
    -- Удалять нельзя — на события в журнале ссылается история проходов.
    blocked     BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_acs_holders_name ON acs_holders (full_name);
CREATE INDEX IF NOT EXISTS idx_acs_holders_blocked
    ON acs_holders (blocked) WHERE blocked = true;

-- ---------------------------------------------------------------------------
-- Двери.
-- ---------------------------------------------------------------------------
--
-- Дверь принадлежит контроллеру, но отличается от него: у одного
-- устройства бывает два проёма. Права выдаются на дверь, а не на
-- контроллер — иначе нельзя было бы, например, пускать подрядчиков
-- только на вход, но не выпускать через служебную дверь.
CREATE TABLE IF NOT EXISTS acs_doors (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    controller_id UUID NOT NULL REFERENCES acs_controllers(id) ON DELETE CASCADE,
    name          VARCHAR(200) NOT NULL,
    -- Направление: in — вход, out — выход, both — двусторонняя.
    -- Нужно потому, что контроллер ведёт раздельные счётчики антипассбэка,
    -- и открытие «не в ту сторону» сбивает учёт проходов.
    direction     VARCHAR(10) NOT NULL DEFAULT 'both',
    -- Локация для показа оператору: «КПП-1, турникет справа».
    location      VARCHAR(200) NOT NULL DEFAULT '',
    -- Дверь может быть выключена: ремонт, консервация проёма.
    enabled       BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT acs_doors_direction_check
        CHECK (direction IN ('in', 'out', 'both'))
);

CREATE INDEX IF NOT EXISTS idx_acs_doors_controller ON acs_doors (controller_id);

-- ---------------------------------------------------------------------------
-- Группы доступа (отделы, бригады, подрядчики).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS acs_groups (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name        VARCHAR(200) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    -- Цвет метки в интерфейсе: помогает различать группы в списках
    -- и в матрице доступа, где их бывает несколько десятков.
    color       VARCHAR(20) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Имя группы уникально: иначе в матрице доступа появятся две одинаковые
-- строки, и оператор не поймёт, какая из них действует.
CREATE UNIQUE INDEX IF NOT EXISTS idx_acs_groups_name ON acs_groups (name);

-- ---------------------------------------------------------------------------
-- Права: какие двери открывает группа.
-- ---------------------------------------------------------------------------
--
-- Матрица доступа — сердце подсистемы. Каждая строка означает «этой
-- группе можно в эту дверь».
--
-- Обратите внимание, что расписания здесь нет намеренно. Пока доступ
-- либо есть, либо нет: расписания (кому когда можно) требуют отдельных
-- таблиц зон времени, и добавлять их «на всякий случай» значило бы
-- усложнить схему до того, как выяснится, нужны ли они. Контроллеру
-- при этом выдаётся полный доступ по времени (tz = 255), а расписания
-- можно ограничить позже, не меняя эту структуру.
CREATE TABLE IF NOT EXISTS acs_group_doors (
    group_id UUID NOT NULL REFERENCES acs_groups(id) ON DELETE CASCADE,
    door_id  UUID NOT NULL REFERENCES acs_doors(id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, door_id)
);

CREATE INDEX IF NOT EXISTS idx_acs_group_doors_door ON acs_group_doors (door_id);

-- ---------------------------------------------------------------------------
-- Состав групп: кто в какой группе.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS acs_holder_groups (
    holder_id UUID NOT NULL REFERENCES acs_holders(id) ON DELETE CASCADE,
    group_id  UUID NOT NULL REFERENCES acs_groups(id) ON DELETE CASCADE,
    PRIMARY KEY (holder_id, group_id)
);

CREATE INDEX IF NOT EXISTS idx_acs_holder_groups_group
    ON acs_holder_groups (group_id);

-- ---------------------------------------------------------------------------
-- Личные разрешения и запреты.
-- ---------------------------------------------------------------------------
--
-- Права человека — это объединение прав его групп. Но иногда нужен
-- точный настрой: новому сотруднику ещё не выдали пропуск на склад,
-- а уборщице нужна одна дверь вне её группы.
--
-- Личная запись перекрывает групповые права, причём в обе стороны:
-- allow = true добавляет дверь, allow = false забирает её, даже если
-- группа разрешает. Запрет важнее разрешения — иначе нельзя было бы
-- закрыть доступ человеку, не убирая его из группы.
CREATE TABLE IF NOT EXISTS acs_holder_doors (
    holder_id UUID NOT NULL REFERENCES acs_holders(id) ON DELETE CASCADE,
    door_id   UUID NOT NULL REFERENCES acs_doors(id) ON DELETE CASCADE,
    allow     BOOLEAN NOT NULL,
    PRIMARY KEY (holder_id, door_id)
);

-- ---------------------------------------------------------------------------
-- Связь карты с владельцем.
-- ---------------------------------------------------------------------------
--
-- Колонка nullable: карта может существовать без владельца — например,
-- прочитанная с контроллера или заведённая заранее, до прихода человека.
-- Такие карты видны в списке и ждут назначения.
ALTER TABLE acs_cards
    ADD COLUMN IF NOT EXISTS holder_id UUID REFERENCES acs_holders(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_acs_cards_holder ON acs_cards (holder_id);

-- ---------------------------------------------------------------------------
-- Владелец вместо прежнего свободного имени.
-- ---------------------------------------------------------------------------
--
-- Переносим уже заведённые имена в новых владельцев: у каждой карты
-- с непустым именем создаём владельца и связываем их.
--
-- Так история не теряется — оператор увидит те же имена, но уже как
-- полноценные карточки людей, к которым можно привязать фото, должность
-- и вторую карту.
INSERT INTO acs_holders (full_name)
SELECT DISTINCT TRIM(name)
FROM acs_cards
WHERE TRIM(name) <> ''
  AND holder_id IS NULL
ON CONFLICT DO NOTHING;

UPDATE acs_cards c
SET holder_id = h.id
FROM acs_holders h
WHERE c.holder_id IS NULL
  AND TRIM(c.name) <> ''
  AND h.full_name = TRIM(c.name);

COMMENT ON TABLE acs_holders IS 'Владельцы карт: сотрудники, проходящие через двери';
COMMENT ON TABLE acs_groups IS 'Группы доступа: отделы, бригады, подрядчики';
COMMENT ON TABLE acs_doors IS 'Двери: проёмы контроллеров, на которые выдаются права';
COMMENT ON COLUMN acs_holders.blocked IS 'Доступ закрыт (увольнение, потеря карты)';
COMMENT ON COLUMN acs_doors.direction IS 'in — вход, out — выход, both — двусторонняя';
COMMENT ON COLUMN acs_holder_doors.allow IS 'true — разрешить дверь, false — запретить (запрет важнее)';
COMMENT ON COLUMN acs_cards.holder_id IS 'Владелец карты; NULL — карта ещё не назначена';
