-- Номер у группы вызова и производитель у абонента.
--
-- Две правки в одной миграции, потому что обе выросли из одной работы над
-- страницей «Домофония» и обе касаются того, как устройство настраивается
-- и вызывается.

-- --------------------------------------------------------------------------
-- Номер группы.
--
-- До этого номер жил только в правиле вызова: правило говорило «набрано 200 —
-- звонить этим». Из-за этого у группы не было своего номера, и в интерфейсе
-- нельзя было ни увидеть, по какому номеру её вызывают, ни поправить его —
-- приходилось искать правило.
--
-- Теперь номер есть у самой группы, а правила остаются для уточнений
-- («с этой панели — в другую группу»).
ALTER TABLE sip_groups
    ADD COLUMN IF NOT EXISTS number TEXT NOT NULL DEFAULT '';

-- Номер должен быть уникальным, если он задан: два правила на один номер
-- в плане набора — это неопределённость, и Asterisk выберет одно из них
-- произвольно.
CREATE UNIQUE INDEX IF NOT EXISTS idx_sip_groups_number
    ON sip_groups (number) WHERE number <> '';

-- Переносим номера из существующих правил без источника: именно они и
-- означали «звонить в эту группу при наборе такого номера».
UPDATE sip_groups g
SET number = r.dialed_number
FROM sip_rules r
WHERE r.group_id = g.id
  AND r.source_account_id IS NULL
  AND g.number = '';

-- --------------------------------------------------------------------------
-- Производитель у абонента.
--
-- Нужен, чтобы понять, каким способом настраивать устройство: у Fanvil это
-- файл конфигурации, у камер OpenIPC — раздел sip в Majestic, у панели
-- Beward — её CGI, а Dahua настраивается только в своём меню. Раньше
-- в карточке предлагался один способ для всех — файл Fanvil, — и для
-- остальных устройств он был бесполезен.
--
-- Где известно — берём у связанной камеры: у неё производитель уже определён
-- сканером.
ALTER TABLE sip_accounts
    ADD COLUMN IF NOT EXISTS vendor TEXT NOT NULL DEFAULT '';

UPDATE sip_accounts a
SET vendor = c.vendor
FROM cameras c
WHERE a.camera_id = c.id
  AND a.vendor = ''
  AND c.vendor <> '';
