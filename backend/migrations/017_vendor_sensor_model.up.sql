-- Дополняем определение производителя.
--
-- Первая попытка (миграция 016) опознала OpenIPC по пустой прошивке и по
-- размеру кадра вида «1920x1080 sub:704x576». Оказалось, что это не все
-- случаи: у части камер сканер записал в прошивку МОДЕЛЬ СЕНСОРА вместе
-- с разрешением — «imx415 3840x2160 sub:704x576», «os02g10_i2c_1080p
-- 1920x1080 sub:704x576».
--
-- Из-за этого четыре камеры остались «неизвестными», и разделы OpenIPC
-- на них скрылись бы — в том числе на 192.168.1.87, которую как раз
-- готовят под распознавание номеров. Ошибка пошла бы не в сторону
-- неудобства, а в сторону потери нужной функции.
--
-- Новый признак: модель сенсора в начале строки. Это тоже след работы
-- сканера, и он надёжен, потому что наименования сенсоров у OpenIPC
-- стандартные. Список намеренно короткий и точный: расширять его
-- «на глазок» нельзя, иначе под OpenIPC попадёт чужая камера, и мы
-- покажем на ней настройки, которых у неё нет.
UPDATE cameras
SET vendor = 'openipc'
WHERE vendor = 'unknown'
  AND (
    -- модель сенсора вместе с разрешением: imx415 3840x2160 sub:704x576
    firmware ~ '^(imx[0-9]+|os[0-9]+[a-z0-9_]*|sc[0-9]+[a-z0-9_]*|gc[0-9]+[a-z0-9_]*|ov[0-9]+[a-z0-9_]*)[[:space:]]'
    OR firmware ILIKE '%sub:%'
    -- прошивка OpenIPC называет себя по имени
    OR firmware ILIKE '%openipc%'
    OR firmware ILIKE '%majestic%'
  );

-- Проверка по факту, а не по предположению: у камеры OpenIPC открыт
-- веб-интерфейс Majestic и она отвечает на /api/v1/config.schema.json.
-- Заполнить это одним UPDATE нельзя, поэтому признак остаётся косвенным,
-- но он точнее, чем ничего: если камера не опознана, оператор задаст
-- производителя вручную в карточке.
UPDATE cameras
SET vendor = 'openipc'
WHERE vendor = 'unknown'
  AND ip IS NOT NULL
  AND firmware LIKE '%x%'
  AND firmware LIKE '%sub%';
