-- Векторы событий для поиска по архиву «по смыслу».
--
-- Зачем отдельная таблица, а не колонка в detection_events. Вектор нужен
-- только поиску по картинке, а событие читают списки, карточки и шкала —
-- на них лишние 2 КБ в каждой строке были бы напрасной работой.
-- Кроме того, векторов может стать по нескольку на событие: при смене
-- модели старые векторы остаются, иначе архив пришлось бы пересчитывать.
CREATE TABLE IF NOT EXISTS event_embeddings (
    -- Событие, к которому относится вектор. Каскад: удалили событие —
    -- ушёл и вектор, отдельных чисток не нужно.
    event_id uuid NOT NULL REFERENCES detection_events(id) ON DELETE CASCADE,
    -- Какая модель посчитала вектор: сравнивать между собой векторы разных
    -- моделей нельзя, а в базе они окажутся рядом после смены модели.
    model text NOT NULL,
    -- Длина вектора. Проверяется при вставке на стороне приложения.
    dim integer NOT NULL CHECK (dim > 0),
    -- Сам вектор: float32 в порядке байт little-endian, dim * 4 байт.
    -- Двоичный формат, а не массив чисел в тексте: 512 float в JSON —
    -- это ~10 КБ на событие вместо 2 КБ.
    vector bytea NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (event_id, model)
);

-- Поиск идёт по окну времени, поэтому нужен обратный проход от события
-- к вектору, а не только по первичному ключу.
CREATE INDEX IF NOT EXISTS idx_event_embeddings_model ON event_embeddings(model);

COMMENT ON TABLE event_embeddings IS
    'Векторы событий (CLIP) для поиска по архиву по текстовому описанию';
