"""
Зона поиска номеров: общий код публикатора кадров и детектора.

Зона задаётся полигоном в долях кадра (0..1), потому что пользователь
рисует её мышью на кадре и после смены разрешения потока координаты
должны остаться верными.

Модуль отдельный не ради красоты: условие «зона задана и по ней можно
резать кадр» нужно в двух местах, и места эти должны отвечать
одинаково. Публикатор кадров (frame_publisher_service) по этому условию
запускает быстрый конвейер зоны, а детектор (main.py) — решает, искать
ли номера на полном кадре. Если условия разойдутся, возможен отказ,
который ничем себя не выдаёт: публикатор решит, что зоны нет, и не
запустит конвейер, а детектор решит, что зона есть, и не станет искать
номера на полном кадре. Номера просто перестанут распознаваться.
"""


def zone_box(zone: list[dict]) -> tuple[float, float, float, float] | None:
    """Превращает полигон зоны в прямоугольник в долях кадра.

    Для поиска номера достаточно прямоугольника: номер — вытянутая область,
    а не сложная фигура. Возвращает (x1, y1, x2, y2) в долях кадра.
    """
    if not zone or len(zone) < 3:
        return None
    try:
        xs = [float(p["x"]) for p in zone]
        ys = [float(p["y"]) for p in zone]
    except (KeyError, TypeError, ValueError):
        return None

    x1, x2 = max(0.0, min(xs)), min(1.0, max(xs))
    y1, y2 = max(0.0, min(ys)), min(1.0, max(ys))
    # Слишком маленькая зона — вероятно, ошибка разметки: не обрезаем вовсе.
    if (x2 - x1) < 0.05 or (y2 - y1) < 0.03:
        return None
    return x1, y1, x2, y2


def has_plate_zone(zone: list[dict] | None) -> bool:
    """Годится ли зона для быстрого конвейера номеров.

    Именно по этому признаку публикатор кадров запускает отдельный поток
    зоны; детектор по нему же решает, что полный кадр этой камеры
    распознаванием номеров занимать не нужно.
    """
    return zone_box(zone or []) is not None
