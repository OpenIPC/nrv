"""Отдача файла карточки и подключение её к панели.

Карточка едет вместе с интеграцией, а не отдельным вложением. Так установка
одного компонента через HACS сразу даёт и сущности, и карточку: иначе
пользователю пришлось бы отдельно скачать файл, положить его в нужный
каталог и зарегистрировать ресурс — три шага, на каждом из которых легко
ошибиться.

Адрес карточки содержит номер версии. Браузер держит файлы ресурсов
в кэше надолго, и без версии в адресе после обновления он продолжал бы
показывать прежнюю карточку, а причина расхождения была бы не видна.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

from homeassistant.components import frontend
from homeassistant.components.http import StaticPathConfig
from homeassistant.core import HomeAssistant

from .const import DOMAIN

_LOGGER = logging.getLogger(__name__)

# Каталог с файлами панели внутри компонента.
FRONTEND_DIR = Path(__file__).parent / "frontend"

# Префикс адресов компонента. Ассистент отдаёт по нему файлы из каталога
# панели, поэтому адрес карточки — это префикс плюс имя файла.
FRONTEND_URL_PREFIX = f"/{DOMAIN}"

# Адрес, по которому отдаётся файл карточки.
CARD_URL_PATH = f"{FRONTEND_URL_PREFIX}/openipc-nvr-card.js"

# Ключ, по которому видно, что файлы панели уже подключены. Регистрация
# идёт один раз на весь ассистент: записей конфигурации может быть
# несколько, а один и тот же файл дважды подключать нельзя — браузер
# загрузит его повторно и объявит карточку второй раз.
_FRONTEND_KEY = f"{DOMAIN}_frontend_registered"


def _read_version() -> str:
    """Читает версию компонента из манифеста.

    Читается один раз при загрузке компонента, а не при каждой настройке.
    Дело не только в экономии: чтение файла внутри асинхронной настройки
    ассистент считает блокирующим вызовом в цикле событий и пишет
    в журнал предупреждение с полной трассировкой. Предупреждение
    безобидное, но выглядит как ошибка, и настоящие ошибки в нём теряются.
    """
    try:
        with open(Path(__file__).parent / "manifest.json", encoding="utf-8") as fh:
            return str(json.load(fh).get("version") or "0")
    except (OSError, ValueError):
        # Версия нужна только для сброса кэша. Без неё карточка продолжит
        # работать, поэтому отсутствие файла не должно ломать настройку.
        return "0"


VERSION = _read_version()


async def async_setup_frontend(hass: HomeAssistant) -> None:
    """Регистрирует файл карточки и подключает его к панели."""
    if hass.data.get(_FRONTEND_KEY):
        return

    try:
        await hass.http.async_register_static_paths(
            [
                StaticPathConfig(
                    # Адресом указывается каталог, а не файл: ассистент
                    # отдаёт по этому адресу файлы из каталога, и при
                    # указании файла запрос к нему самого себя давал отказ
                    # в доступе вместо раздачи файла.
                    FRONTEND_URL_PREFIX,
                    str(FRONTEND_DIR),
                    # Управление кэшем выключено: версия стоит в адресе,
                    # и её изменение само заставит браузер взять новый файл.
                    cache_headers=False,
                )
            ]
        )
    except RuntimeError:
        # Путь может быть уже занят после перезагрузки компонента без
        # перезапуска ассистента. Это не ошибка: файл уже отдаётся.
        _LOGGER.debug("Адрес карточки уже зарегистрирован")

    frontend.add_extra_js_url(hass, f"{CARD_URL_PATH}?v={VERSION}")
    hass.data[_FRONTEND_KEY] = True
