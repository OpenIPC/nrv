#!/usr/bin/env bash
#
# Общие проверки перед установкой NVR — одинаковые для Astra, Debian и Ubuntu.
#
# Файл не запускается сам по себе: его подключают скрипты подготовки
# (scripts/prepare-astra.sh, scripts/prepare-debian.sh). Так проверки живут
# в одном месте и не расходятся между системами.
#
# Что проверяем и почему:
#
#   * Порты. Если порт занят чужой службой, `docker compose up` падает уже
#     после сборки образов: часть контейнеров остаётся в статусе Created, и
#     это выглядит как «установилось, но не работает». Так было на Astra, где
#     порт внешнего RTSP держала другая система видеонаблюдения.
#
#   * Место на диске. Сборка образа детектора занимает от 1 ГБ (обычный
#     процессор) до 8 ГБ (сборка с CUDA). Проверять нужно там, где Docker
#     действительно хранит образы, а это не всегда /var/lib/docker —
#     см. preflight_disk.

# Порты, которые публикует наш сервер (см. docker-compose.yml).
NVR_PORTS="3001 8080 9784 8555"

# Сколько свободного места считаем достаточным. Порог с запасом: при
# пересборке старый и новый слои образа живут одновременно до очистки кэша.
NVR_MIN_FREE_MB=20480

# preflight_ports — предупредить о портах, занятых чужими службами.
#
# Порты наших же контейнеров (docker-proxy, go2rtc) — не конфликт, а признак
# повторной установки: их отмечаем отдельно и тревоги не поднимаем. Иначе
# предупреждение срабатывает при каждом обновлении и перестаёт читаться.
preflight_ports() {
    local busy=0 port owner proc

    echo "--- Порты ---"
    for port in $NVR_PORTS; do
        # Фильтр по порту средствами ss: не зависит от того, слушает служба
        # IPv4 или IPv6, и не требует разбирать вывод глазами.
        owner="$(ss -tlnpH "sport = :${port}" 2>/dev/null | head -1 || true)"
        [ -n "$owner" ] || continue

        proc="$(printf '%s' "$owner" | sed -n 's/.*users:((\"\([^\"]*\)\".*/\1/p')"
        case "$proc" in
            docker-proxy|go2rtc|nginx|server)
                printf 'занят %-5s нашим сервером (%s) — для повторной установки это нормально\n' \
                    "$port" "$proc"
                ;;
            *)
                busy=1
                printf 'занят %-5s ЧУЖОЙ службой: %s\n' "$port" "${proc:-неизвестный процесс}"
                ;;
        esac
    done

    if [ "$busy" -eq 0 ]; then
        echo "конфликтов нет"
        return 0
    fi

    cat <<'EOF'

Порт, занятый чужой службой, нужно освободить до установки: иначе `docker
compose up` упадёт после сборки образов, часть контейнеров останется в
статусе Created, и это будет выглядеть как «установилось, но не работает».
Чаще всего мешает другая система видеонаблюдения (например, «Линия» держит
9780/9784/9786, а 9784 нужен нам для внешнего RTSP). Варианты:
  * остановить чужую службу: systemctl disable --now <служба>;
  * отказаться от внешнего RTSP: убрать публикацию порта 9784 в сервисе
    rtsp-proxy (docker-compose.yml).
EOF
}

# preflight_disk — проверить место там, где Docker действительно хранит образы.
preflight_disk() {
    local dir=/var/lib/docker free_mb

    # До Docker 25 слои образов лежали в /var/lib/docker. Начиная с 25 (и на
    # Astra с Docker 29) используется containerd-snapshotter, и всё переехало
    # в /var/lib/containerd. Перенос «Docker на большой диск», сделанный
    # только для /var/lib/docker, оставляет данные на прежнем маленьком
    # разделе — и сборка падает с «No space left on device», хотя df по
    # /var/lib/docker показывает терабайты.
    if command -v docker >/dev/null 2>&1 && docker info 2>/dev/null | grep -q 'io.containerd.snapshotter'; then
        dir=/var/lib/containerd
    fi

    free_mb="$(df -Pm "$dir" 2>/dev/null | awk 'NR == 2 {print $4}')"
    echo "--- Место на диске ---"
    if [ -z "${free_mb:-}" ]; then
        # Каталога может не быть до первой установки Docker — это не повод
        # останавливать установку: compose сам разложит данные.
        echo "каталог $dir ещё не создан — проверка не нужна"
        return 0
    fi

    echo "$dir: свободно $((free_mb / 1024)) ГБ"
    if [ "$free_mb" -lt "$NVR_MIN_FREE_MB" ]; then
        cat <<EOF

ВНИМАНИЕ: свободного места меньше $((NVR_MIN_FREE_MB / 1024)) ГБ. Сборке
образа детектора может не хватить (с CUDA это около 8 ГБ). Что делать —
docs/INSTALL-DISTROS.md, раздел «Где Docker хранит данные»: перенести
каталог $dir на большой раздел и закрепить переносом в /etc/fstab.
EOF
    fi
}

# Библиотека не запускается сама: при прямом вызове подсказываем, что нужно.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    echo "Это библиотека проверок, запускать её отдельно не нужно." >&2
    echo "Используйте: sudo bash scripts/prepare-astra.sh" >&2
    echo "         или: sudo bash scripts/prepare-debian.sh" >&2
    exit 2
fi
